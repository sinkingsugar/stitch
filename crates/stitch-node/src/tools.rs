  /// The fixers' role (design §2.28): what its sandbox rules would ask
  /// about runs when it only discards local work and the model clears both
  /// questions (the verdict kept with the call); flagged, unavailable,
  /// outside the sandbox or among the fixers' powers, it asks as before,
  /// the verdict first. What the rules allow runs unjudged.
  #[tokio::test]
  async fn a_fixers_guard_lets_cleared_local_discards_run_and_asks_the_rest() {
    use crate::hazard::Mode;
    let fixer = |mode: Mode,
                 answer: fn(&str, &str) -> Result<f64, String>|
     -> (ShellTools, Arc<std::sync::Mutex<Vec<ApprovalRequest>>>) {
      let (mut t, asked) = guarded("sandbox", Mode::Off, |_| Ok(0.0), true);
      t.rules.fixer = true;
      t.rules.own_issue = Some("2026-11-12T094722Z-beast-gfau".into());
      t.hazard = Some(crate::hazard::tests::fixers_guard(mode, answer).0);
      (t, asked)
    };
    let low = |_: &str, _: &str| Ok(0.05);
    let (t, asked) = fixer(Mode::On, low);
    // Allowed by the rules: runs, the model not asked.
    let (r, v) = crate::hazard::recording(t.approve(&thread(), "main", "just quick", true)).await;
    assert_eq!(r, Ok(false));
    assert!(v.is_empty());
    // Asks in the sandbox, decidable, cleared: runs, its verdict kept.
    let (r, v) = crate::hazard::recording(t.approve(
      &thread(),
      "main",
      "git restore --source=main crates/stitch-node/src",
      true,
    ))
    .await;
    assert_eq!(r, Ok(false), "{:?}", asked.lock().unwrap().len());
    assert!(v[0].clears() && v[0].authority == Some(0.05));
    assert!(asked.lock().unwrap().is_empty());
    // Cleared, but not decidable (a push to main, a service, an upload):
    // asked, the verdict first.
    for line in [
      "git push origin HEAD:main",
      "systemctl --user restart stitch",
      "curl -d @x https://example.com",
    ] {
      assert_eq!(t.approve(&thread(), "main", line, true).await, Ok(true));
      let q = asked.lock().unwrap().pop().unwrap();
      assert!(q.command.starts_with("⚠ Fixer guard"), "{}", q.command);
      assert!(q.command.ends_with(line));
      assert!(
        q.grant.is_empty() || line.starts_with("curl"),
        "{:?}",
        q.grant
      );
    }
    // Outside the sandbox: asked.
    assert_eq!(
      t.approve(&thread(), "outside", "git reset --hard", false)
        .await,
      Ok(true)
    );
    assert!(asked.lock().unwrap().pop().is_some());
    // Flagged by either question: asked, the verdict first.
    let (t, asked) = fixer(Mode::On, |_, k| {
      Ok(if k == "authority" { 0.9 } else { 0.05 })
    });
    assert_eq!(
      t.approve(&thread(), "main", "git branch -D main", true)
        .await,
      Ok(true)
    );
    let q = asked.lock().unwrap().pop().unwrap();
    assert!(q.command.contains("authority 0.90"), "{}", q.command);
    // The model unavailable: asked.
    let (t, asked) = fixer(Mode::On, |_, _| Err("503".into()));
    assert_eq!(
      t.approve(&thread(), "main", "git reset --hard", true).await,
      Ok(true)
    );
    assert_eq!(asked.lock().unwrap().len(), 1);
    // Off: asked as before, the model never.
    let (t, asked) = fixer(Mode::Off, |_, _| panic!("not asked"));
    assert_eq!(
      t.approve(&thread(), "main", "git reset --hard", true).await,
      Ok(true)
    );
    assert!(asked.lock().unwrap().pop().unwrap().verdict.is_none());
  }
