/// The node's built-in tools, shared by attached and detached threads.
pub(crate) struct NodeTools {
  pub shell: ShellTools,
  /// The node's web tools, shared by every loop.
  pub web: std::sync::Arc<crate::web::Web>,
  /// The search key, read once for the loop.
  pub search_key: Option<String>,
  /// Where images the model saw are, for `zoom_image`.
  pub blobs: stitch_store::BlobStore,
  /// Where `view_file` and `zoom_image` put what they make.
  pub scratch: PathBuf,
  /// The model the loop runs on (`provider/model`), for the tools'
  /// descriptions: the node's default until the loop's is known.
  pub model: String,
  pub memory: std::sync::Arc<crate::memory::Memory>,
  pub state: std::sync::Arc<stitch_net::NodeState>,
  /// The node, for `spawn`, `send`, `wait` and `models`.
  pub shared: std::sync::Weak<crate::node::Shared>,
  /// The user's other nodes, by name: where `spawn` can send work.
  pub peers: Vec<String>,
  /// Tools from the MCP servers the thread enables.
  pub mcp: crate::mcp::McpTools,
  /// Tools written in Otter, from the thread's skills.
  pub otter: crate::otter::OtterTools,
  /// The built-in groups the thread's tool set has on (`crate::toolset`).
  pub groups: Vec<&'static str>,
  /// Its skills whose files are another node's, for `read_skill`.
  pub remote_skills: Vec<crate::toolset::RemoteSkill>,
  /// `write_file` and `edit_file`: where they run at once, and the asking.
  pub edits: crate::edits::Editing,
  /// When this loop started: a Stop pressed in the browser after it ends
  /// its use of the browser (design §2.18).
  pub started: std::time::Instant,
  /// A user is at a client of this node: browser sessions start
  /// cooperative, in their window (else agent-alone).
  pub attended: bool,
  /// The image model behind `generate_image` (`provider/model`); `None`
  /// when the node has none it can ask.
  pub image_model: Option<String>,
  /// A chat the user is in: a turn at its step limit asks them for more
  /// (`ToolRunner::more_steps`).
  pub asks_more_steps: bool,
  /// An app's thread's guard (design §2.22): every call passes it first,
  /// and every model call its money check.
  pub guard: Option<std::sync::Arc<crate::apps::guard::Guard>>,
  /// The capability profiles holding the loop (docs/events.md): the
  /// schedule's that started the turn, and its thread's taint, read at
  /// each call. Every call passes it first, `Tool.Call`s included.
  pub ceiling: crate::profile::Ceiling,
}

impl NodeTools {
  /// An app's thread's call (design §2.22): its guard decides first,
  /// before anything of it runs; what it lets run is dispatched here,
  /// and only what it lists.
  fn guarded<'a>(
    &'a self,
    guard: &'a std::sync::Arc<crate::apps::guard::Guard>,
    thread: &'a RecordId,
    call: &'a str,
    name: &'a str,
    input: &'a Value,
  ) -> BoxFuture<'a, ToolOutcome> {
    use crate::apps::guard::Verdict;
    Box::pin(async move {
      let input = match guard.authorize(name, input, &self.otter, &self.mcp) {
        Verdict::Refuse(why) => return ToolOutcome::err(why),
        Verdict::Run => input.clone(),
        Verdict::RunWith(i) => i,
        Verdict::Ask(command) => {
          // The user's to approve, the app named (`threads::approver`).
          let Some(approver) = &self.shell.approver else {
            return ToolOutcome::err(
              "this needs the user's approval, and nobody is here to give it",
            );
          };
          let d = approver(ApprovalRequest::new(
            thread.clone(),
            "files".into(),
            command,
          ))
          .await;
          if !d.allow {
            return ToolOutcome::err(match d.reason {
              Some(r) => format!("the user declined: {r}"),
              None => "the user declined".into(),
            });
          }
          // Approved: written as approved, not asked again.
          let mut edits = self.edits.clone();
          edits.yolo = true;
          edits.approver = None;
          let mut out = edits.call(thread, name, input).await;
          if out.ok {
            out.output = format!("(approved by the user)\n{}", out.output);
          }
          return out;
        }
      };
      match name {
        "view_file" => {
          crate::viewer::view(&input, &self.shell.cwd, &self.edits.aliases, &self.scratch).await
        }
        "zoom_image" => crate::viewer::zoom(&input, &self.blobs, &self.scratch).await,
        "write_file" | "edit_file" => {
          // Authorized for its place: written without asking.
          let mut edits = self.edits.clone();
          edits.yolo = true;
          edits.approver = None;
          edits.call(thread, name, &input).await
        }
        "browse_web" => self.web.browse_public(&input).await,
        "search_web" => {
          self
            .web
            .call(name, &input, self.search_key.as_deref())
            .await
        }
        "generate_image" => match &self.image_model {
          Some(m) => {
            let mut out = crate::imagegen::generate(
              self.shared.upgrade(),
              self.blobs.clone(),
              m.clone(),
              input,
            )
            .await;
            // Priced, so the loop's budgets count it.
            if let Some(spent) = &mut out.spent
              && spent.usd.is_none()
            {
              spent.usd = crate::pricing::priced(&spent.model, &spent.usage, None);
            }
            out
          }
          None => ToolOutcome::err("generate_image needs an image model this node can ask"),
        },
        "read_skill" => self.dispatch(thread, call, name, &input).await,
        // Priced to the thread, so the grant's money counts it; admitted
        // first, as a step is (the grant, the thread's and the family's
        // money), each call, a script's nested ones too.
        "decide" => {
          if let Some(why) = guard.admit().await {
            return ToolOutcome::err(why);
          }
          crate::decide::tool::call(self.shared.upgrade(), thread, &input).await
        }
        "app_command" | "app_shell" => {
          let (Some(s), Some(n)) = (guard.shared(), guard.needs()) else {
            return ToolOutcome::err("the grant no longer stands");
          };
          crate::apps::containers::call(&s, &guard.owner, &n, name, &input).await
        }
        _ if self.otter.has(name) => self.otter.call(thread, name, &input).await,
        _ if self.mcp.has(name) => self.mcp.call(thread, name, &input).await,
        _ => ToolOutcome::err(format!("{name} is not run for an app's thread")),
      }
    })
  }

  fn on(&self, group: &str) -> bool {
    self.groups.contains(&group)
  }

  /// `read_skill` is offered: skills not here, or with lazy tools.
  fn reads_skills(&self) -> bool {
    !self.remote_skills.is_empty() || !self.otter.lazy_skills().is_empty()
  }

  /// What a call of a tool this loop does not offer says: which it is and
  /// how to turn it on, never an unknown tool's silence.
  fn not_offered(&self, thread: &RecordId, name: &str) -> String {
    use crate::toolset::{group_of, how_to_change};
    if let Some(g) = group_of(name) {
      return if self.on(g) {
        format!("{name} is not available on this node.")
      } else {
        format!(
          "{name} is off for this thread (the {g} tools). The user can turn them on with {}.",
          how_to_change(thread, g, true)
        )
      };
    }
    if let Some(why) = self.mcp.why_not(thread, name) {
      return why;
    }
    match name.split_once("__") {
      Some((server, _)) => format!(
        "{name}: no MCP server {server} on this node, nor shared by another of the user's nodes."
      ),
      None => format!("no tool {name}"),
    }
  }
}

impl NodeTools {
  /// Whether `thread` is a room's participant.
  fn in_room(&self, thread: &RecordId) -> bool {
    self
      .shared
      .upgrade()
      .is_some_and(|s| crate::rooms::room_of(&s, thread).is_some())
  }

  /// Runs a call the thread's tool set offers (an app's thread's, once
  /// its guard let it).
  fn dispatch<'a>(
    &'a self,
    thread: &'a RecordId,
    call: &'a str,
    name: &'a str,
    input: &'a Value,
  ) -> BoxFuture<'a, ToolOutcome> {
    match name {
      "browse_web" | "web_eval" | "search_web" => {
        // An app's address here (`show_app` gives it without the token):
        // the node's own browser gets in.
        let admitted = self
          .shared
          .upgrade()
          .and_then(|s| {
            let url = input.get("url")?.as_str()?;
            s.apps.desktop.get()?.admit(url)
          })
          .map(|url| {
            let mut i = input.clone();
            i["url"] = url.into();
            i
          });
        match admitted {
          Some(i) => {
            let (web, key) = (self.web.clone(), self.search_key.clone());
            let name = name.to_owned();
            Box::pin(async move { web.call(&name, &i, key.as_deref()).await })
          }
          None => Box::pin(self.web.call(name, input, self.search_key.as_deref())),
        }
      }
      "view_file" => {
        // A fixer's, sandboxed or not.
        let unreadable = if self.shell.rules.fixer {
          crate::fixer::unreadable(&self.shell.env)
        } else {
          Vec::new()
        };
        match crate::viewer::unreadable(input, &self.shell.cwd, &unreadable) {
          Some(why) => Box::pin(async move { ToolOutcome::err(why) }),
          None => Box::pin(crate::viewer::view(
            input,
            &self.shell.cwd,
            &self.edits.aliases,
            &self.scratch,
          )),
        }
      }
      "write_file" | "edit_file" => Box::pin(self.edits.call(thread, name, input)),
      "commit_push" => {
        let (shared, repo) = (self.shared.upgrade(), self.edits.clone_of.clone());
        let (editing, thread, input) = (self.edits.clone(), thread.clone(), input.clone());
        Box::pin(async move {
          match (shared, repo) {
            (Some(s), Some(repo)) => crate::clones::tool(s, editing, thread, repo, input).await,
            _ => ToolOutcome::err("commit_push works in a project's clone on a phone"),
          }
        })
      }
      "show_app" => Box::pin(crate::apps::show(
        self.shared.upgrade(),
        self.edits.cwd.clone(),
        thread.clone(),
        input.clone(),
      )),
      "zoom_image" => Box::pin(crate::viewer::zoom(input, &self.blobs, &self.scratch)),
      "decide" => Box::pin(crate::decide::tool::call(
        self.shared.upgrade(),
        thread,
        input,
      )),
      "generate_image" => match &self.image_model {
        Some(m) => Box::pin(crate::imagegen::generate(
          self.shared.upgrade(),
          self.blobs.clone(),
          m.clone(),
          input.clone(),
        )),
        None => Box::pin(async {
          ToolOutcome::err(
            "generate_image needs an image model this node can ask: a Gemini key \
             (`stitch key set gemini`), or `[images] model` in config.toml",
          )
        }),
      },
      "spawn" | "send" | "wait" | "models" => Box::pin(crate::weave::tool(
        self.shared.clone(),
        thread.clone(),
        call.to_owned(),
        name.to_owned(),
        input.clone(),
      )),
      "schedule" | "wake_at" => {
        let (shared, thread, input) = (self.shared.upgrade(), thread.clone(), input.clone());
        let asker = self.shell.asker();
        let name = name.to_owned();
        Box::pin(async move {
          let Some(s) = shared else {
            return ToolOutcome::err("the node is stopping");
          };
          let r = if name == "wake_at" {
            match serde_json::from_value(input) {
              Ok(i) => crate::schedules::wake_at(&s, &thread, i).await,
              Err(e) => Err(crate::Error::Config(e.to_string())),
            }
          } else {
            match serde_json::from_value(input) {
              Ok(i) => {
                let caller = crate::schedules::Caller::Thread {
                  id: &thread,
                  asker: &asker,
                };
                crate::schedules::act(&s, caller, i).await
              }
              Err(e) => Err(crate::Error::Config(e.to_string())),
            }
          };
          crate::weave::outcome(r)
        })
      }
      "subscribe" | "event_reply" => {
        let (shared, thread, input) = (self.shared.upgrade(), thread.clone(), input.clone());
        let asker = self.shell.asker();
        let name = name.to_owned();
        Box::pin(async move {
          let Some(s) = shared else {
            return ToolOutcome::err("the node is stopping");
          };
          crate::weave::outcome(if name == "subscribe" {
            crate::events::tool_subscribe(&s, &thread, &asker, input).await
          } else {
            crate::events::tool_reply(&s, &thread, &input)
          })
        })
      }
      // Rendered from the thread's own transcript, which nobody reads for a
      // room participant: refused there (issue 2026-11-21T070413Z-gamer-58iv).
      "suggest_replies" | "offer_actions" if self.in_room(thread) => {
        let out = ToolOutcome::err(format!(
          "{name} does not show in a room: its buttons would not reach the user. Ask in words."
        ));
        Box::pin(async move { out })
      }
      // Shown at once: the transcript has the call, clients its buttons.
      "suggest_replies" => {
        let out = crate::replies::call(input);
        Box::pin(async move { out })
      }
      // Checked against this loop's own tools, then shown (design §2.30).
      "offer_actions" => Box::pin(crate::actions::call(self, input)),
      "notify" => {
        let (shared, thread, input) = (self.shared.upgrade(), thread.clone(), input.clone());
        Box::pin(async move {
          let Some(s) = shared else {
            return ToolOutcome::err("the node is stopping");
          };
          crate::weave::outcome(crate::notices::tool(&s, &thread, input).await)
        })
      }
      "report_issue" | "self_improve" => {
        let (shared, thread, input) = (self.shared.upgrade(), thread.clone(), input.clone());
        let asker = self.shell.asker();
        let name = name.to_owned();
        Box::pin(async move {
          let Some(s) = shared else {
            return ToolOutcome::err("the node is stopping");
          };
          crate::weave::outcome(if name == "report_issue" {
            crate::issues::tool(&s, &thread, input).await
          } else {
            crate::selfimprove::tool(&s, &thread, &asker, input).await
          })
        })
      }
      "threads" | "cancel" => {
        let (shared, thread, input) = (self.shared.upgrade(), thread.clone(), input.clone());
        let asker = self.shell.asker();
        let name = name.to_owned();
        Box::pin(async move {
          let Some(s) = shared else {
            return ToolOutcome::err("the node is stopping");
          };
          crate::weave::thread_tool(&s, &thread, &name, input, &asker).await
        })
      }
      // Reads synced records alone: no approval, read-only threads too.
      "read_thread" => {
        let (shared, input) = (self.shared.upgrade(), input.clone());
        Box::pin(async move {
          let Some(s) = shared else {
            return ToolOutcome::err("the node is stopping");
          };
          let s2 = s.clone();
          let r = tokio::task::spawn_blocking(move || crate::scopes::read_thread(&s2, input))
            .await
            .unwrap_or_else(|e| Err(crate::Error::Config(e.to_string())));
          // What another thread's tools printed may hold secrets.
          match r {
            Ok(text) => ToolOutcome::ok(s.vault.redact(&text)),
            Err(e) => ToolOutcome::err(s.vault.redact(&e.to_string())),
          }
        })
      }
      "recall" => {
        // Kept to a scope: its threads, and their exact matches, found
        // here (memory off or on).
        let scope: Vec<String> = input
          .get("scope")
          .and_then(Value::as_array)
          .map(|a| {
            a.iter()
              .filter_map(Value::as_str)
              .map(str::to_owned)
              .collect()
          })
          .unwrap_or_default();
        if scope.is_empty() {
          return Box::pin(self.memory.recall_tool(&self.state, thread, input, None));
        }
        let (shared, query) = (
          self.shared.upgrade(),
          input
            .get("query")
            .and_then(Value::as_str)
            .unwrap_or("")
            .to_owned(),
        );
        Box::pin(async move {
          let Some(s) = shared else {
            return ToolOutcome::err("the node is stopping");
          };
          let s2 = s.clone();
          let found =
            tokio::task::spawn_blocking(move || crate::scopes::scope_search(&s2, &scope, &query))
              .await
              .unwrap_or_else(|e| Err(crate::Error::Config(e.to_string())));
          match found {
            Ok(f) => {
              let mut out = self
                .memory
                .recall_tool(&self.state, thread, input, Some(&f))
                .await;
              out.output = s.vault.redact(&out.output);
              out
            }
            Err(e) => ToolOutcome::err(e.to_string()),
          }
        })
      }
      n if crate::personal::CALENDAR_TOOLS.contains(&n)
        || crate::personal::MAPS_TOOLS.contains(&n) =>
      {
        let Some(host) = crate::personal::host() else {
          let why = format!(
            "{name} is not available on this node: the user's calendar, reminders and maps \
             are the phone's (spawn on it)"
          );
          return Box::pin(async move { ToolOutcome::err(why) });
        };
        let asker = self.shell.asker();
        Box::pin(async move { crate::personal::call(host, &asker, thread, name, input).await })
      }
      n if n.starts_with("browser_") => {
        let shared = self.shared.upgrade();
        let asker = self.shell.asker();
        let (started, attended, scratch) = (self.started, self.attended, self.scratch.clone());
        let cwd = self.edits.cwd.clone();
        let (thread, name, input) = (thread.clone(), name.to_owned(), input.clone());
        Box::pin(async move {
          let Some(s) = shared else {
            return ToolOutcome::err("the node is stopping");
          };
          let key = thread.to_string();
          // The tab group is named after the thread.
          let title = s
            .state()
            .index
            .lock()
            .expect("index lock")
            .title(&thread)
            .ok()
            .flatten()
            .unwrap_or_else(|| key.rsplit('-').next().unwrap_or("").to_owned());
          let placed = s.thread_place(&thread).ok();
          let place = placed.as_ref().map(|(_, p)| p.key());
          // Pages of the user's own browser stay out of memory (design
          // §2.18): a thread that uses it is taken out of memory, unless
          // the user switched its memory themselves (`/memory on` brings
          // it back).
          let mut memory_note = None;
          if let Some((root, _)) = &placed
            && !s.memory.is_switched(&thread)
            && !s.memory.is_off(&thread)
            && s
              .memory
              .remember(s.state(), root, &thread, false)
              .unwrap_or(false)
          {
            memory_note = Some(
              "[This thread is out of memory now: pages of the user's browser are not remembered. The user can bring it back with /memory on.]",
            );
          }
          let ctx = crate::browser::engine::CallCtx {
            thread: &key,
            title,
            place,
            cwd: Some(cwd),
            asker: &asker,
            thread_id: Some(&thread),
            started,
            attended,
            scratch: &scratch,
          };
          let mut out = s
            .browsers
            .engine
            .call(&s.browsers, &ctx, &name, &input)
            .await;
          if let Some(n) = memory_note {
            out.output = format!("{}\n{n}", out.output);
          }
          out
        })
      }
      "read_skill" => {
        let wanted = input.get("name").and_then(Value::as_str).unwrap_or("");
        let file = input.get("file").and_then(Value::as_str);
        let lazy = self.otter.lazy_section(wanted).unwrap_or_default();
        let here = self
          .otter
          .lazy_skills()
          .into_iter()
          .find(|(k, _)| k == wanted)
          .and_then(|(_, f)| f);
        let out = match (self.remote_skills.iter().find(|k| k.name == wanted), file) {
          (Some(k), None) => {
            let mut text = format!("[{} SKILL.md, from {}]\n{}", k.name, k.node, k.text);
            if !k.files.is_empty() {
              let names: Vec<&str> = k.files.iter().map(|(p, _)| p.as_str()).collect();
              text.push_str(&format!(
                "\n[Its files, read with read_skill and file: {}]",
                names.join(", ")
              ));
            }
            text.push_str(&lazy);
            ToolOutcome::ok(text)
          }
          // A skill here with lazy tools: its file, and them.
          (None, None) if here.is_some() => {
            let path = here.expect("checked");
            match std::fs::read_to_string(&path) {
              Ok(t) => ToolOutcome::ok(format!("[{wanted} {}]\n{t}{lazy}", path.display())),
              Err(e) => ToolOutcome::err(format!("{}: {e}", path.display())),
            }
          }
          (Some(k), Some(f)) => match k.files.iter().find(|(p, _)| p == f) {
            Some((p, t)) => ToolOutcome::ok(format!("[{} {p}]\n{t}", k.name)),
            None => ToolOutcome::err(format!(
              "{} has no file {f}; it has: {}",
              k.name,
              k.files
                .iter()
                .map(|(p, _)| p.as_str())
                .collect::<Vec<_>>()
                .join(", ")
            )),
          },
          (None, _) => ToolOutcome::err(format!(
            "no skill {wanted} to read this way; the others are files, read with the shell"
          )),
        };
        Box::pin(async move { out })
      }
      // A script's `Tool.Call`s come back to this dispatcher, each the
      // thread's own call, approved as its tool is (`crate::otter::calls`).
      "otter_run" if self.otter.has(name) => Box::pin(async move {
        let dispatch = move |n: String, i: Value| -> BoxFuture<'a, ToolOutcome> {
          Box::pin(async move { self.call(thread, call, &n, &i).await })
        };
        self
          .otter
          .call_with(thread, name, input, Some(&dispatch))
          .await
      }),
      _ if self.otter.has(name) => self.otter.call(thread, name, input),
      _ if self.mcp.has(name) => self.mcp.call(thread, name, input),
      _ => self.shell.call(thread, call, name, input),
    }
  }
}

impl ToolRunner for NodeTools {
  fn prepare(&self) -> BoxFuture<'_, ()> {
    Box::pin(self.mcp.prepare())
  }

  fn definitions(&self) -> Vec<ToolDef> {
    let mut out = Vec::new();
    // Where no program can start (iOS, visionOS), only for SSH hosts
    // (`ShellTools::definitions` offers none without).
    if self.on("shell") {
      out.extend(self.shell.definitions());
    }
    if self.on("viewer") {
      out.extend(crate::viewer::definitions());
    }
    if self.on("files") {
      out.extend(crate::edits::definitions());
      if self.edits.clone_of.is_some() {
        out.push(crate::clones::definition());
      }
    }
    if self.on("web") {
      out.extend(self.web.definitions(self.search_key.is_some()));
    }
    if self.on("weave") {
      out.extend(crate::weave::definitions(
        &self.peers,
        self.state.node.as_str(),
        &self.model,
      ));
      out.push(crate::scopes::definition());
      out.extend(crate::schedules::definitions());
      out.extend(crate::events::definitions());
      out.push(crate::notices::definition());
      out.push(crate::replies::definition());
      out.push(crate::actions::definition());
      out.push(crate::issues::definition());
    }
    if self.on("self_improve") {
      let places = self
        .shared
        .upgrade()
        .map(|s| crate::selfimprove::places(&s))
        .unwrap_or_default();
      out.push(crate::selfimprove::definition(&places));
    }
    if self.on("apps") {
      out.extend(crate::apps::definitions());
    }
    if self.on("decide") {
      out.push(crate::decide::tool::definition());
    }
    if self.on("browser")
      && let Some(s) = self.shared.upgrade()
      && s.browsers.any_enabled()
    {
      out.extend(crate::browser::engine::definitions());
    }
    if self.on("memory") && self.memory.available() {
      out.push(crate::memory::Memory::definition());
    }
    // The device's calendar, reminders and maps, where the app lends them
    // (design §2.3).
    out.extend(crate::personal::definitions(
      self.on("calendar"),
      self.on("maps"),
    ));
    if self.on("images")
      && let Some(m) = &self.image_model
    {
      out.push(crate::imagegen::definition(m));
    }
    if self.reads_skills() {
      let mut names: Vec<String> = self.remote_skills.iter().map(|k| k.name.clone()).collect();
      let lazy: Vec<String> = self
        .otter
        .lazy_skills()
        .into_iter()
        .map(|(k, _)| k)
        .filter(|k| !names.contains(k))
        .collect();
      let mut description = format!(
        "The SKILL.md of a skill that is not a file here (built into Stitch, or on another of the user's machines): {}.",
        names.join(", ")
      );
      if !lazy.is_empty() {
        description.push_str(&format!(
          " Also a skill here whose tools are lazy (not in the tool list; called with Tool.Call in otter_run), with their parameters: {}.",
          lazy.join(", ")
        ));
        names.extend(lazy);
      }
      out.push(ToolDef {
        name: "read_skill".into(),
        description,
        input_schema: json!({
          "type": "object", "additionalProperties": false,
          "properties": {
            "name": {"type": "string", "description": "The skill's name."},
            "file": {"type": "string", "description": "One of its files instead of SKILL.md, by the path SKILL.md gives (references/…, assets/…)."}
          },
          "required": ["name"]
        }),
      });
    }
    out.extend(self.otter.definitions());
    out.extend(self.mcp.definitions());
    // An app's thread's containers, as its grants stand (design §2.23).
    if let Some(g) = &self.guard
      && let Some(s) = g.shared()
      && g.needs().is_some()
    {
      out.extend(crate::apps::containers::definitions(&s, &g.owner));
    }
    // Held by a profile: only what it allows is listed (a call to the
    // rest is refused all the same).
    let profiles = self.ceiling.profiles();
    if !profiles.is_empty() {
      out.retain(|d| profiles.iter().all(|p| p.allows_tool(&d.name)));
    }
    out
  }

  fn call<'a>(
    &'a self,
    thread: &'a RecordId,
    call: &'a str,
    name: &'a str,
    input: &'a Value,
  ) -> BoxFuture<'a, ToolOutcome> {
    let offered = match crate::toolset::group_of(name) {
      Some(g) => self.on(g),
      None if name == "read_skill" => self.reads_skills(),
      None if name == "app_command" || name == "app_shell" => self.guard.is_some(),
      None => self.otter.has(name) || self.mcp.has(name),
    };
    if !offered {
      let why = self.not_offered(thread, name);
      return Box::pin(async move { ToolOutcome::err(why) });
    }
    if let Some(why) = self.ceiling.refuses(name) {
      return Box::pin(async move { ToolOutcome::err(why) });
    }
    if let Some(guard) = &self.guard {
      return self.guarded(guard, thread, call, name, input);
    }
    self.dispatch(thread, call, name, input)
  }

  fn interrupt<'a>(
    &'a self,
    thread: &'a RecordId,
    name: &'a str,
    input: &'a Value,
  ) -> BoxFuture<'a, ()> {
    // A script's calls were dropped with it: commands they entered in
    // shells are being stopped, as for an interrupted shell_run.
    let name = if name == "otter_run" {
      "shell_run"
    } else {
      name
    };
    self.shell.interrupt(thread, name, input)
  }

  fn redact(&self, text: String) -> String {
    match self.shared.upgrade() {
      Some(s) => s.vault.redact(&text),
      None => text,
    }
  }

  fn admit<'a>(&'a self, _thread: &'a RecordId) -> BoxFuture<'a, Option<String>> {
    Box::pin(async move {
      match &self.guard {
        Some(g) => g.admit().await,
        None => None,
      }
    })
  }

  fn metered(
    &self,
    _thread: &RecordId,
    model: &str,
    usage: &stitch_providers::Usage,
    usd: Option<f64>,
  ) {
    if let Some(g) = &self.guard {
      g.metered(model, usage, usd);
    }
  }

  fn more_steps<'a>(&'a self, thread: &'a RecordId, taken: u64, more: u64) -> BoxFuture<'a, bool> {
    Box::pin(async move {
      let Some(approver) = self
        .shell
        .approver
        .as_ref()
        .filter(|_| self.asks_more_steps)
      else {
        return false;
      };
      let request = ApprovalRequest::new(
        thread.clone(),
        STEPS_SESSION.to_owned(),
        format!("Continue for {more} more steps? This turn has taken {taken} and is not done"),
      );
      approver(request).await.allow
    })
  }
}

