/// The shell helper, which forks shells on macOS
/// (`stitch_shell::helper_main`): `STITCH_SHELL_HELPER` when set (a build
/// of one's own, a test's), else `stitch-shell-helper` next to this binary.
/// Said once in the node's log when it is not there; shells then start
/// through `/bin/sh`.
fn shell_helper() -> Option<&'static PathBuf> {
  static HELPER: std::sync::OnceLock<Option<PathBuf>> = std::sync::OnceLock::new();
  HELPER
    .get_or_init(|| {
      let exe = std::env::current_exe().ok();
      let helper = helper_named(std::env::var_os("STITCH_SHELL_HELPER"), exe.as_deref())?;
      if helper.is_file() {
        return Some(helper);
      }
      // A test of the node's runs from cargo's `deps/`, and the helper
      // built with it is one level up.
      if let Some(built) = exe.as_deref().and_then(helper_built_beside_test)
        && built.is_file()
      {
        return Some(built);
      }
      if cfg!(target_os = "macos") {
        eprintln!(
          "shells: {} is missing (it is built and installed with stitch, \
           e.g. `cargo install --path crates/stitch-cli`, or named by \
           STITCH_SHELL_HELPER); shells start through /bin/sh, where bash \
           jobs may now and then say \"child setpgid … Operation not \
           permitted\"",
          helper.display()
        );
      }
      None
    })
    .as_ref()
}

/// Whether this node can sandbox shells (`stitch_shell::Sandbox`); when
/// not, said once in the node's log, and the `sandbox` mode asks as `ask`
/// does.
pub(crate) fn sandbox_available() -> bool {
  static AVAILABLE: std::sync::OnceLock<bool> = std::sync::OnceLock::new();
  *AVAILABLE.get_or_init(|| {
    match stitch_shell::Sandbox::available(shell_helper().map(PathBuf::as_path)) {
      Ok(()) => true,
      Err(why) => {
        if stitch_shell::CAN_SPAWN {
          eprintln!("shells: no sandbox here ({why}); commands ask as in the `ask` mode");
        }
        false
      }
    }
  })
}

/// Which shell helper: the one `STITCH_SHELL_HELPER` names, else the one
/// next to the node's binary.
fn helper_named(set: Option<std::ffi::OsString>, exe: Option<&Path>) -> Option<PathBuf> {
  set
    .filter(|s| !s.is_empty())
    .map(PathBuf::from)
    .or_else(|| exe.map(|e| e.with_file_name("stitch-shell-helper")))
}

/// For a test binary in cargo's target directory (`…/debug/deps/<test>`),
/// the helper cargo builds with the workspace (`…/debug/stitch-shell-helper`).
fn helper_built_beside_test(exe: &Path) -> Option<PathBuf> {
  let deps = exe.parent()?;
  (deps.file_name()? == "deps").then(|| deps.parent().map(|d| d.join("stitch-shell-helper")))?
}

fn describe(o: &stitch_shell::Outcome) -> ToolOutcome {
  let state = match &o.status {
    Status::AtPrompt { exit } => format!("exit {exit}"),
    Status::Running { program, .. } => {
      format!(
        "still running: {program} (after {:.1}s)",
        o.elapsed.as_secs_f64()
      )
    }
    Status::Closed => "the session has ended".into(),
  };
  let mut out = state;
  if !o.output.is_empty() {
    out.push_str("\n\n");
    out.push_str(&o.output);
  }
  if let Some(screen) = &o.screen {
    out.push_str("\n\n[screen]\n");
    out.push_str(screen.trim_end());
  }
  ToolOutcome {
    ok: !matches!(o.status, Status::Closed),
    output: out,
    images: Vec::new(),
    spent: None,
    attachments: Vec::new(),
    blobs: Vec::new(),
    generated: Vec::new(),
  }
}

impl ShellTools {
  /// A session to run a command in: the thread's of that name, or a new
  /// one (`true`), which the result says.
  async fn session(
    &self,
    thread: &RecordId,
    name: &str,
    cwd: Option<&str>,
    outside: bool,
  ) -> Result<(Session, bool), String> {
    if let Some((host, there)) = remote_of(name) {
      return self.remote_session(thread, name, host, there).await;
    }
    let key = format!("{thread}:{name}");
    // A read-only room participant's command the user allowed once runs
    // in a session started writable (design §2.27); the next call starts
    // it again read-only.
    let once = self.rules.is_read_only()
      && self
        .rules
        .room_ask
        .as_ref()
        .is_some_and(|a| a.take_once(&key));
    let read_only = self.rules.is_read_only() && !once;
    {
      let mut sessions = self.shells.sessions.lock().await;
      if let Some(s) = sessions.get(&key)
        && s.status() != Status::Closed
      {
        let started_read_only = self
          .shells
          .read_only
          .lock()
          .expect("read-only lock")
          .contains(&key);
        // A session started writable never serves a read-only thread (what
        // runs in it ends); one started read-only starts again writable
        // once it is idle.
        let running = matches!(s.status(), Status::Running { .. });
        if once && started_read_only && running {
          return Err(format!(
            "session \"{name}\" is running something in the read-only sandbox: run the command \
             the user allowed in another session"
          ));
        }
        let stale = if read_only {
          !started_read_only
        } else {
          started_read_only && !running
        };
        if !stale {
          return Ok((s.clone(), false));
        }
        let old = sessions.remove(&key);
        drop(sessions);
        if let Some(old) = old {
          old.close().await;
        }
      }
    }
    // Started without the sessions' lock, which every thread's calls take:
    // a shell slow to start holds up nobody else.
    let mut cfg = ShellConfig::new(self.start_dir(cwd));
    cfg.env = self.env.clone();
    if let Some(place_env) = &self.place_env {
      for (k, v) in (place_env.0)() {
        cfg.env.retain(|(e, _)| *e != k);
        cfg.env.push((k, v));
      }
    }
    cfg.clean_env = self.clean_env;
    cfg.env.push(("STITCH_THREAD".into(), thread.to_string()));
    // A fixer's: no SSH agent, no forge token, git with no credential
    // helper, inside the sandbox or outside it (docs/self-improve.md §5).
    if self.rules.fixer {
      crate::fixer::env_added(true, &mut cfg.env);
      cfg.env_remove = crate::fixer::ENV_REMOVED
        .iter()
        .map(|k| (*k).to_owned())
        .collect();
    }
    cfg.shell = self.kind.clone();
    cfg.redact = self.redact.clone();
    if let Some(helper) = shell_helper() {
      cfg.helper = Some(helper.clone());
    }
    if !outside {
      cfg.sandbox = if read_only {
        self.read_only_sandbox.clone()
      } else {
        self.sandbox.clone()
      };
    }
    let s = match Session::spawn(cfg).await {
      Ok(s) => s,
      Err(e) => {
        // In the node's log too: a node that cannot start shells any more
        // is diagnosed from there.
        eprintln!("session {key} did not start: {e}");
        return Err(e.to_string());
      }
    };
    let mut sessions = self.shells.sessions.lock().await;
    if let Some(other) = sessions.get(&key)
      && other.status() != Status::Closed
    {
      // Another call of the thread started one meanwhile: that one stays.
      let other = other.clone();
      drop(sessions);
      s.close().await;
      return Ok((other, false));
    }
    {
      let mut on_purpose = self.shells.outside.lock().expect("outside lock");
      if outside && self.sandbox.is_some() {
        on_purpose.insert(key.clone());
      } else {
        on_purpose.remove(&key);
      }
    }
    {
      let mut started = self.shells.read_only.lock().expect("read-only lock");
      if read_only {
        started.insert(key.clone());
      } else {
        started.remove(&key);
      }
    }
    {
      // Not a writable session a switch to read-only left: what closes
      // those (`Shared::close_switched`, after any sync, the one asking the
      // question started included) leaves it to run the command allowed.
      let mut allowed = self.shells.once.lock().expect("once lock");
      if once {
        allowed.insert(key.clone());
      } else {
        allowed.remove(&key);
      }
    }
    sessions.insert(key, s.clone());
    Ok((s, true))
  }

  /// A session that is there: what is typed, looked at or waited on is
  /// never a new shell that took its name (one after a restart would get
  /// text meant for the program the session ran).
  async fn existing(&self, thread: &RecordId, name: &str) -> Result<Session, String> {
    // A session on a host whose connection dropped is made again: in tmux
    // the same one, picked up where it was.
    if let Some((host, there)) = remote_of(name)
      && let Some(s) = self.ssh.as_ref().and_then(std::sync::Weak::upgrade)
      && s.ssh.dropped(&session_key(thread, name))
    {
      return self
        .remote_session(thread, name, host, there)
        .await
        .map(|(s, _)| s);
    }
    match self
      .shells
      .sessions
      .lock()
      .await
      .get(&session_key(thread, name))
    {
      Some(s) if s.status() != Status::Closed => Ok(s.clone()),
      Some(_) => Err(format!(
        "session {name} has ended (its shell exited): start a new one with shell_run"
      )),
      None => Err(format!(
        "no session {name} here (sessions end when the node restarts): start one with shell_run"
      )),
    }
  }

  /// A session on a host: the thread's of that name, or one opened (a
  /// connection made, or made again after it dropped), what happened said
  /// in `notes`.
  async fn remote_session(
    &self,
    thread: &RecordId,
    name: &str,
    host: &str,
    there: &str,
  ) -> Result<(Session, bool), String> {
    let Some(shared) = self.ssh.as_ref().and_then(std::sync::Weak::upgrade) else {
      return Err("SSH is not available here".into());
    };
    let key = session_key(thread, name);
    if let Some(s) = self.shells.sessions.lock().await.get(&key)
      && s.status() != Status::Closed
    {
      return Ok((s.clone(), false));
    }
    // Opened without the sessions' lock (a host may be slow to answer).
    let opened = crate::ssh::open(
      &shared,
      crate::ssh::Open {
        thread: thread.as_str(),
        host,
        session: there,
        key: &key,
        redact: self.redact.clone(),
      },
    )
    .await;
    let (s, note) = opened.map_err(|e| format!("session \"{there}\" on {host}: {e}"))?;
    let mut sessions = self.shells.sessions.lock().await;
    if let Some(other) = sessions.get(&key)
      && other.status() != Status::Closed
    {
      // Another call opened it meanwhile (the same tmux session): that
      // one stays, this client goes without closing what it shows.
      return Ok((other.clone(), false));
    }
    if let Some(note) = note {
      self.notes.lock().expect("notes lock").push(note);
    }
    sessions.insert(key, s.clone());
    Ok((s, true))
  }

  /// Whether a command for session `name` runs sandboxed: as the session
  /// there runs, else as it will start (`outside` it, or not). Outside
  /// cannot name a sandboxed session. A session that runs otherwise than
  /// this loop's mode says (sandboxed from before yolo was turned on, or
  /// unsandboxed from yolo once the sandbox is back, not started `outside`
  /// on purpose) starts again first: `restart` says so.
  async fn sandboxed(
    &self,
    thread: &RecordId,
    name: &str,
    outside: bool,
  ) -> Result<(bool, Restart), String> {
    // A host has no sandbox of this node's.
    if remote_of(name).is_some() {
      return Ok((false, Restart::No));
    }
    let key = session_key(thread, name);
    let running = self
      .shells
      .sessions
      .lock()
      .await
      .get(&key)
      .map(|s| (s.sandboxed(), s.status()))
      .filter(|(_, status)| *status != Status::Closed);
    let on_purpose = || {
      self
        .shells
        .outside
        .lock()
        .expect("outside lock")
        .contains(&key)
    };
    let running =
      running.map(|(sandboxed, status)| (sandboxed, matches!(status, Status::Running { .. })));
    let stale = match running {
      Some((true, _)) => self.sandbox.is_none(),
      Some((false, _)) => self.sandbox.is_some() && !outside && !on_purpose(),
      None => false,
    };
    if stale && running.is_some_and(|(_, busy)| busy) {
      let (was, now) = if self.sandbox.is_none() {
        ("in", "outside")
      } else {
        ("outside", "in")
      };
      return Err(format!(
        "session {name} was started {was} the sandbox before the shell's mode changed, and a \
         program runs in it; it must start again {now} the sandbox. Stop what runs there (or \
         shell_close it), or use another session."
      ));
    }
    let running = running.map(|(sandboxed, _)| sandboxed);
    match running {
      Some(true) if outside => Err(format!(
        "session {name} runs in the sandbox: run outside it in another session (leave session \
         out for \"outside\")"
      )),
      Some(true) if self.sandbox.is_none() => Ok((false, Restart::Outside)),
      Some(false) if self.sandbox.is_some() && !outside && !on_purpose() => {
        Ok((true, Restart::Inside))
      }
      Some(sandboxed) => Ok((sandboxed, Restart::No)),
      None => Ok((!outside && self.sandbox.is_some(), Restart::No)),
    }
  }

  /// Ends a session that must start again (`sandboxed`), once the command
  /// for it may run; what its result says of it.
  async fn restart(&self, thread: &RecordId, name: &str, restart: Restart) -> Option<String> {
    let said = match restart {
      Restart::No => return None,
      Restart::Outside => format!(
        "(Session \"{name}\" ran in the sandbox from before; restarted outside it: fresh \
         directory and environment.)"
      ),
      Restart::Inside => format!(
        "(Session \"{name}\" ran outside the sandbox from before (yolo); restarted in it: fresh \
         directory and environment.)"
      ),
    };
    let key = session_key(thread, name);
    let old = self.shells.sessions.lock().await.remove(&key);
    if let Some(s) = old {
      s.close().await;
    }
    Some(said)
  }

  /// `Ok(true)` when the user approved it, `Ok(false)` when the rules did;
  /// `sandboxed`: in a sandboxed session, where only what reaches beyond
  /// the sandbox asks.
  async fn approve(
    &self,
    thread: &RecordId,
    session: &str,
    command: &str,
    sandboxed: bool,
  ) -> Result<bool, String> {
    self
      .approve_in(thread, session, command, sandboxed, None, false)
      .await
  }

  /// `approve`, the command to run in `start` when given (a session about
  /// to start there, `cwd`), else where the session is now. A file the
  /// guard read that changed before the command runs (while the model or
  /// the user was asked) is judged again (design §2.28).
  async fn approve_in(
    &self,
    thread: &RecordId,
    session: &str,
    command: &str,
    sandboxed: bool,
    start: Option<PathBuf>,
    lift: bool,
  ) -> Result<bool, String> {
    let mut asked = false;
    for _ in 0..3 {
      let (r, verdict) = self
        .approve_once(thread, session, command, sandboxed, start.clone(), lift)
        .await;
      let r = r?;
      asked |= r;
      if !verdict.as_ref().is_some_and(crate::hazard::Verdict::stale) {
        return Ok(asked);
      }
    }
    Err(
      "not run: the files this command runs kept changing while the hazard guard judged them"
        .into(),
    )
  }

  async fn approve_once(
    &self,
    thread: &RecordId,
    session: &str,
    command: &str,
    sandboxed: bool,
    start: Option<PathBuf>,
    lift: bool,
  ) -> (Result<bool, String>, Option<crate::hazard::Verdict>) {
    let mut verdict = None;
    let r = self
      .judged(
        thread,
        session,
        command,
        sandboxed,
        start,
        lift,
        &mut verdict,
      )
      .await;
    (r, verdict)
  }

  #[allow(clippy::too_many_arguments)]
  async fn judged(
    &self,
    thread: &RecordId,
    session: &str,
    command: &str,
    sandboxed: bool,
    start: Option<PathBuf>,
    lift: bool,
    kept: &mut Option<crate::hazard::Verdict>,
  ) -> Result<bool, String> {
    // A read-only thread's sandboxed session writes only temporary
    // directories: its rules there refuse only what acts beyond it
    // (`Rules::allows_sandboxed`); unsandboxed, its allowlist holds.
    // On a host: as its record's `approval` says (design §2.20).
    let remote = remote_of(session).map(|(host, _)| {
      self
        .ssh
        .as_ref()
        .and_then(std::sync::Weak::upgrade)
        .and_then(|s| crate::ssh::host(&s, host))
        .map(|h| crate::ssh::approval_of(&h))
        .unwrap_or_default()
    });
    let allows = move |rules: &Rules, line: &str| match remote {
      Some(approval) => rules.allows_remote(line, approval),
      None if sandboxed => rules.allows_sandboxed(line),
      None => rules.allows(line),
    };
    let allowed = allows(&self.rules, command);
    let fixers = self
      .hazard
      .as_ref()
      .is_some_and(|g| g.role == crate::hazard::Role::Fixers);
    // A fixer's (and the triage's) guard judges only what would ask: in
    // its sandbox, its rules and the sandbox are the bound of what runs.
    if fixers && allowed {
      return Ok(false);
    }
    // The hazard guard (design §2.28; the user's threads in auto mode, a
    // fixer's in self-improvement's auto mode) judges what runs and what
    // asks alike: a verdict on what would run may make it ask; one on what
    // asks anyway goes with the question.
    let verdict = match &self.hazard {
      Some(g) if !self.rules.is_read_only() && !(fixers && g.off()) => {
        let host = remote_of(session).map(|(h, _)| h.to_owned());
        let cwd = match (&host, start) {
          (Some(_), _) => None,
          (None, Some(d)) => Some(d),
          (None, None) => Some(self.session_dir(thread, session).await),
        };
        g.check(crate::hazard::Action::Shell {
          line: command.to_owned(),
          cwd,
          host,
        })
        .await
      }
      _ => None,
    };
    if let Some(v) = &verdict {
      crate::hazard::record(v);
    }
    kept.clone_from(&verdict);
    // The fixers' role (design §2.28): what would ask runs when it stays
    // in the sandbox, is decidable (only discards local work, nothing
    // `fixer_guarded` names: `Rules::fixer_decidable`) and the model clears
    // both questions; the verdict is kept with the call.
    if fixers
      && crate::hazard::fixers::clears(
        verdict.as_ref(),
        sandboxed,
        remote.is_some(),
        &self.rules,
        command,
      )
    {
      return Ok(false);
    }
    // Auto mode without a verdict (design §2.28): what needed one does
    // not run, rather than run unjudged; the agent relays why.
    if allowed && let Some(v) = verdict.as_ref().filter(|v| v.fails()) {
      return Err(crate::hazard::unavailable(v));
    }
    let guarded = allowed && verdict.as_ref().is_some_and(crate::hazard::Verdict::asks);
    if allowed && !guarded {
      return Ok(false);
    }
    if self.rules.is_read_only()
      && lift
      && remote.is_none()
      && let (Some(ask), Some(approver)) = (&self.rules.room_ask, &self.approver)
    {
      // A read-only room participant asks the user, who is in the room
      // (design §2.27): allowed once, the command runs in a session
      // started writable (as a writable thread's would: its sandbox);
      // "always", the thread is writable from then on.
      let d = approver(ApprovalRequest::room(
        thread.clone(),
        session,
        ask,
        &format!("run `{command}`"),
      ))
      .await;
      ask.decided(&d, &format!("`{command}`"))?;
      if !d.always {
        ask.allow_once(&session_key(thread, session));
      }
      return Ok(true);
    }
    if self.rules.is_read_only() {
      return Err(format!(
        "this thread is read-only: `{command}` is not among what the rules allow, so it is \
         refused, never asked. Use read-only commands (shell_run's description lists them), \
         or report what needs doing."
      ));
    }
    let stopped = |v: &Option<crate::hazard::Verdict>| {
      v.as_ref()
        .filter(|_| guarded)
        .map(crate::hazard::declined)
        .unwrap_or_default()
    };
    let Some(approver) = &self.approver else {
      return Err(format!(
        "this command needs the user's approval, and nobody is here to give it{}",
        stopped(&verdict)
      ));
    };
    let rules = self.rules.clone();
    let line = command.to_owned();
    // What the guard stopped is asked as it is; an "always" answer would
    // grant nothing the rules do not already allow.
    let grant = match remote {
      _ if guarded => None,
      Some(approval) => self.rules.grantable_remote(command, approval),
      None if sandboxed => self.rules.grantable_sandboxed(command),
      None => self.rules.grantable(command),
    };
    let request = ApprovalRequest {
      grant: grant.unwrap_or_default(),
      allowed_now: (!guarded).then(|| -> Arc<dyn Fn() -> bool + Send + Sync> {
        Arc::new(move || allows(&rules, &line))
      }),
      verdict: verdict.clone(),
      user_only: guarded || (fixers && verdict.is_some()),
      ..ApprovalRequest::new(
        thread.clone(),
        session.to_owned(),
        crate::hazard::question(command, verdict.as_ref()),
      )
    };
    let decision = approver(request).await;
    if decision.allow {
      Ok(true)
    } else {
      Err(match decision.reason {
        Some(reason) => format!(
          "the user declined this command: {reason}{}",
          stopped(&verdict)
        ),
        None => format!("the user declined this command{}", stopped(&verdict)),
      })
    }
  }

  /// Where a session started with `cwd` starts (relative: from where this
  /// loop's sessions start).
  fn start_dir(&self, cwd: Option<&str>) -> PathBuf {
    cwd.map_or_else(|| self.cwd.clone(), |c| self.cwd.join(c))
  }

  /// Where a command runs when its session is to start (none yet, or
  /// started again): the guard judges the files there (design §2.28).
  async fn starting_in(
    &self,
    thread: &RecordId,
    session: &str,
    cwd: Option<&str>,
    restart: bool,
  ) -> Option<PathBuf> {
    let exists = self
      .shells
      .sessions
      .lock()
      .await
      .contains_key(&session_key(thread, session));
    (!exists || restart).then(|| self.start_dir(cwd))
  }

  /// Where a session runs now (its shell's directory), else where this
  /// loop's sessions start.
  async fn session_dir(&self, thread: &RecordId, name: &str) -> PathBuf {
    let pid = self
      .shells
      .sessions
      .lock()
      .await
      .get(&session_key(thread, name))
      .and_then(Session::shell_pid);
    let fallback = self.cwd.clone();
    tokio::task::spawn_blocking(move || crate::hazard::session_dir(pid, &fallback))
      .await
      .unwrap_or_else(|_| self.cwd.clone())
  }

  /// `job_stop`: a job of this thread at once; another thread's (`all`)
  /// once the user approved it.
  async fn job_stop(&self, thread: &RecordId, input: &Value) -> ToolOutcome {
    let from = match input.get("signal").and_then(Value::as_str) {
      None => crate::jobs::StopFrom::Int,
      Some(s) => match crate::jobs::StopFrom::parse(s) {
        Some(f) => f,
        None => return ToolOutcome::err(format!("signal `{s}`: int, term or kill")),
      },
    };
    let grace = input
      .get("grace_secs")
      .map_or(crate::jobs::STOP_GRACE, |_| {
        secs(input, "grace_secs", 5.0, 60.0)
      });
    let id = input.get("job").and_then(Value::as_u64);
    let session = input.get("session").and_then(Value::as_str);
    let on_host = session.zip(input.get("host").and_then(Value::as_str));
    let on_host = on_host.map(|(s, h)| format!("{s}@{h}"));
    let session = on_host.as_deref().or(session);
    let r = match (id, session) {
      (Some(_), Some(_)) => Err("give job or session, not both".to_owned()),
      (None, None) => Err("missing `job` (or `session`)".to_owned()),
      (None, Some(name)) => self.shells.stop_in_session(thread, name, from, grace).await,
      (Some(id), None) => {
        let all = input.get("all").and_then(Value::as_bool) == Some(true);
        match self.shells.owner_of(id) {
          Some((owner, what)) if &owner != thread => {
            if !all {
              Err(format!(
                "job {id} is another thread's ({owner}): job_stop with all asks the user to \
                 stop it"
              ))
            } else if let Err(e) = self
              .approve_other(thread, &format!("job_stop {id}: {what} of thread {owner}"))
              .await
            {
              Err(e)
            } else {
              self.shells.stop_job(id, None, from, grace).await
            }
          }
          _ => self.shells.stop_job(id, Some(thread), from, grace).await,
        }
      }
    };
    match r {
      Ok(text) => ToolOutcome::ok(text),
      Err(e) => ToolOutcome::err(e),
    }
  }

  async fn approve_other(&self, thread: &RecordId, what: &str) -> Result<(), String> {
    self.asker().ask(thread, "jobs", what).await
  }

  /// Who asks the user about acting on another thread's work.
  pub(crate) fn asker(&self) -> Asker {
    Asker {
      approver: self.approver.clone(),
      read_only: self.rules.is_read_only(),
      yolo: crate::rules::runs_unasked(&self.rules.mode),
    }
  }

  /// A call, minding what a person typed into its session (attached):
  /// nothing is sent on top of it, and a look reports it.
  async fn run(&self, thread: &RecordId, name: &str, input: &Value) -> ToolOutcome {
    let mut out = self.run_typed(thread, name, input).await;
    // What happened to a remote session on the way (a reconnect, a host
    // without tmux), said first.
    let notes: Vec<String> = std::mem::take(&mut *self.notes.lock().expect("notes lock"));
    if !notes.is_empty() {
      out.output = format!("{}\n\n{}", notes.join("\n"), out.output);
    }
    out
  }

  async fn run_typed(&self, thread: &RecordId, name: &str, input: &Value) -> ToolOutcome {
    let session_name = input
      .get("session")
      .and_then(Value::as_str)
      .unwrap_or("main");
    let remote_name = input
      .get("host")
      .and_then(Value::as_str)
      .map(|h| format!("{session_name}@{h}"));
    let session_name = remote_name.as_deref().unwrap_or(session_name);
    let session = self
      .shells
      .sessions
      .lock()
      .await
      .get(&session_key(thread, session_name))
      .cloned();
    // Only the session tools: others (watch_file, unwatch) do not touch a
    // session, nor take what was typed into one.
    if !name.starts_with("shell_") {
      return self.run_inner(thread, name, input).await;
    }
    let sends = matches!(name, "shell_run" | "shell_send");
    // Said before asking for an approval; typing during it is minded as
    // the input is written (`Error::Typed`).
    if sends && let Some(typed) = session.as_ref().and_then(Session::take_typed) {
      return typed_over(session_name, &typed);
    }
    let mut out = self.run_inner(thread, name, input).await;
    if !sends && let Some(typed) = session.as_ref().and_then(Session::take_typed) {
      out.output = format!(
        "{}\n\n{}",
        crate::jobs::typed_note(session_name, &typed),
        out.output
      );
    }
    out
  }

  async fn run_inner(&self, thread: &RecordId, name: &str, input: &Value) -> ToolOutcome {
    if self.rules.mode == "off" {
      return ToolOutcome::err("the shell is turned off on this node");
    }
    let background =
      name == "shell_run" && input.get("background").and_then(Value::as_bool) == Some(true);
    let host = input.get("host").and_then(Value::as_str);
    if let Some(h) = host {
      if self.ssh.is_none() {
        return ToolOutcome::err("SSH is not available here");
      }
      if name == "watch_file" {
        return ToolOutcome::err(format!(
          "watch_file watches files on this machine, not on {h}: on a host, watch a command \
           instead (shell_run with background, e.g. `tail -f <file>`, then shell_watch with \
           pattern)"
        ));
      }
    } else if !stitch_shell::CAN_SPAWN && name.starts_with("shell_") {
      return ToolOutcome::err(
        "no shell runs on this device: give `host` (one of the SSH hosts) to run there",
      );
    }
    // Outside the sandbox only where there is one.
    let outside = name == "shell_run"
      && host.is_none()
      && self.sandbox.is_some()
      && input.get("outside").and_then(Value::as_bool) == Some(true);
    // A background command gets a session of its own unless one is named.
    let session_name = match input.get("session").and_then(Value::as_str) {
      Some(s) if s.contains('@') => {
        return ToolOutcome::err(format!(
          "session `{s}`: a session's name has no `@` (give `host` for a session on a host)"
        ));
      }
      Some(s) => s.to_owned(),
      None if background => format!("bg{}", self.shells.last_job.load(Ordering::Relaxed) + 1),
      None if outside => "outside".to_owned(),
      None => "main".to_owned(),
    };
    // On a host, a session is keyed by its name there.
    let session_name = match host {
      Some(h) => format!("{session_name}@{h}"),
      None => session_name,
    };
    let session_name = session_name.as_str();
    match name {
      "shell_run" if background => {
        let Some(command) = input.get("command").and_then(Value::as_str) else {
          return ToolOutcome::err("missing `command`");
        };
        let (sandboxed, restart) = match self.sandboxed(thread, session_name, outside).await {
          Ok(sandboxed) => sandboxed,
          Err(e) => return ToolOutcome::err(e),
        };
        let cwd = input.get("cwd").and_then(Value::as_str);
        let start = self
          .starting_in(thread, session_name, cwd, restart != Restart::No)
          .await;
        let approved = match self
          .approve_in(thread, session_name, command, sandboxed, start, true)
          .await
        {
          Ok(approved) => approved,
          Err(e) => return ToolOutcome::err(e),
        };
        let restarted = self.restart(thread, session_name, restart).await;
        let (session, created) = match self.session(thread, session_name, cwd, !sandboxed).await {
          Ok(s) => s,
          Err(e) => return ToolOutcome::err(e),
        };
        let named = input.get("session").is_some();
        if !named {
          // Its own session, closed once the command ends.
          self.shells.mark_auto(thread, session_name);
        }
        // A moment to fail at once (a typo, a missing file) before it is a job.
        let waiting = Waiting::new(&self.shells, thread, session_name, &session);
        let o = session
          .run(command, Wait::prompt(Duration::from_secs(1)))
          .await;
        waiting.done();
        let out = match o {
          Ok(o) if matches!(o.status, Status::Running { .. }) => {
            let limit = limit_of(input);
            let id = self.shells.watch(
              thread,
              On::Session {
                name: session_name.to_owned(),
                session,
                until: Until::Done,
              },
              limit,
            );
            let mut out = noted(describe(&o), approved);
            let limited = match limit.max {
              Some(max) if limit.stop => {
                format!(" or after {}, when it is stopped", crate::jobs::spoken(max))
              }
              Some(max) => format!(" or after {}, when it runs on", crate::jobs::spoken(max)),
              None => String::new(),
            };
            out.output = format!(
              "Running in the background as job {id}, in session \"{session_name}\": you are told when it ends{limited}. shell_wait waits for it, shell_view shows it, job_output {{\"job\": {id}}} has its output, job_stop {{\"job\": {id}}} stops it (and the processes it started).\n\n{}",
              out.output
            );
            out
          }
          Ok(o) => {
            let mut out = noted(describe(&o), approved);
            out.output = format!("It ended at once, so it is no job.\n\n{}", out.output);
            if self.shells.close_auto(thread, session_name).await {
              out.output.push_str(&format!(
                "\n\n[Session \"{session_name}\" is closed with it.]"
              ));
            }
            out
          }
          Err(e) => failed(session_name, e),
        };
        // A session of its own (none named) is new by design: nothing to say.
        restarted_noted(
          restarted,
          fresh(
            created && named && restart == Restart::No,
            session_name,
            out,
          ),
        )
      }
      "shell_watch" => {
        let until = match until_of(input) {
          Ok(u) => u,
          Err(e) => return ToolOutcome::err(e),
        };
        let key = session_key(thread, session_name);
        let Some(session) = self.shells.sessions.lock().await.get(&key).cloned() else {
          return ToolOutcome::err(format!("no session {session_name}"));
        };
        if matches!(until, Until::Done) && !session.command().is_some_and(|c| c.running) {
          return ToolOutcome::err(format!("nothing runs in session {session_name}"));
        }
        let limit = limit_of(input);
        let runs = session.command().is_some_and(|c| c.running);
        let what = format!(
          "{}{}",
          crate::jobs::condition_of(&until),
          crate::jobs::limit_said(limit, runs)
        );
        let id = self.shells.watch(
          thread,
          On::Session {
            name: session_name.to_owned(),
            session,
            until,
          },
          limit,
        );
        ToolOutcome::ok(format!(
          "Watching as job {id}: {}.",
          what
            .replacen("tells when it", "you are told when it", 1)
            .replacen("tells when", "you are told when", 1)
        ))
      }
      "shell_wait" => {
        let until = match until_of(input) {
          Ok(u) => u,
          Err(e) => return ToolOutcome::err(e),
        };
        let key = session_key(thread, session_name);
        let Some(session) = self.shells.sessions.lock().await.get(&key).cloned() else {
          return ToolOutcome::err(format!("no session {session_name}"));
        };
        let secs = input
          .get("timeout_secs")
          .and_then(Value::as_u64)
          .unwrap_or(600);
        let timeout = (secs > 0).then(|| Duration::from_secs(secs));
        match session.wait_for(&until, timeout).await {
          Ok(w) => {
            let mut said = Vec::new();
            match (&w.matched, w.done, &until) {
              (Some(line), _, _) if !line.is_empty() => said.push(format!("matched: {line}")),
              (Some(_), _, _) => said.push("the screen is as asked".into()),
              (None, false, _) => {
                said.push(format!("not yet, after {}", spoken(w.outcome.elapsed)))
              }
              (None, true, _) => {}
            }
            if w.done {
              // Had here: its jobs need not tell of it.
              let gone = self.shells.forget(thread, session_name);
              if !gone.is_empty() {
                let ids: Vec<String> = gone.iter().map(u64::to_string).collect();
                said.push(format!("job {} is done with", ids.join(", ")));
              }
              if self.shells.close_auto(thread, session_name).await {
                said.push(format!("session \"{session_name}\" is closed with it"));
              }
            }
            let mut out = describe(&w.outcome);
            if matches!(until, Until::Screen(_)) && w.outcome.screen.is_none() {
              out.output.push_str(&format!(
                "\n\n[screen]\n{}",
                session.screen().text.trim_end()
              ));
            }
            if !said.is_empty() {
              out.output = format!("{}\n\n{}", said.join("; "), out.output);
            }
            out
          }
          Err(e) => ToolOutcome::err(e.to_string()),
        }
      }
      "watch_file" => {
        let Some(path) = input.get("path").and_then(Value::as_str) else {
          return ToolOutcome::err("missing `path`");
        };
        let path = expand_home(path);
        let path = if path.is_absolute() {
          path
        } else {
          self.cwd.join(path)
        };
        let line = match regex_of(input, "pattern") {
          Ok(r) => r,
          Err(e) => return ToolOutcome::err(e),
        };
        let until = crate::jobs::FileUntil {
          line,
          quiet: quiet_of(input),
        };
        let limit = limit_of(input);
        let what = format!(
          "{}{}",
          crate::jobs::file_condition_of(&until),
          crate::jobs::limit_said(limit, false)
        );
        let shown = path.display().to_string();
        let id = self.shells.watch(thread, On::File { path, until }, limit);
        ToolOutcome::ok(format!(
          "Watching {shown} as job {id}: {}.",
          what.replacen("tells when", "you are told when", 1)
        ))
      }
      "unwatch" => {
        let Some(id) = input.get("job").and_then(Value::as_u64) else {
          return ToolOutcome::err("missing `job`");
        };
        if self.shells.cancel(id, Some(thread)) {
          ToolOutcome::ok(format!("job {id} cancelled"))
        } else {
          ToolOutcome::err(format!("no job {id} of this thread"))
        }
      }
      "jobs" => {
        let all = input.get("all").and_then(Value::as_bool) == Some(true);
        ToolOutcome::ok(self.shells.jobs_text((!all).then_some(thread)).await)
      }
      "job_output" => {
        let Some(id) = input.get("job").and_then(Value::as_u64) else {
          return ToolOutcome::err("missing `job`");
        };
        let all = input.get("all").and_then(Value::as_bool) == Some(true);
        let n = |k: &str| {
          input
            .get(k)
            .and_then(Value::as_u64)
            .map(|v| usize::try_from(v).unwrap_or(usize::MAX))
        };
        match self
          .shells
          .job_output(id, (!all).then_some(thread), n("lines"), n("from"))
          .await
        {
          Ok(text) => ToolOutcome::ok(text),
          Err(e) => ToolOutcome::err(e),
        }
      }
      "job_stop" => self.job_stop(thread, input).await,
      "shell_run" => {
        let Some(command) = input.get("command").and_then(Value::as_str) else {
          return ToolOutcome::err("missing `command`");
        };
        let (sandboxed, restart) = match self.sandboxed(thread, session_name, outside).await {
          Ok(sandboxed) => sandboxed,
          Err(e) => return ToolOutcome::err(e),
        };
        let cwd = input.get("cwd").and_then(Value::as_str);
        let start = self
          .starting_in(thread, session_name, cwd, restart != Restart::No)
          .await;
        let approved = match self
          .approve_in(thread, session_name, command, sandboxed, start, true)
          .await
        {
          Ok(approved) => approved,
          Err(e) => return ToolOutcome::err(e),
        };
        let restarted = self.restart(thread, session_name, restart).await;
        let (session, created) = match self.session(thread, session_name, cwd, !sandboxed).await {
          Ok(s) => s,
          Err(e) => return ToolOutcome::err(e),
        };
        let screen = match regex_of(input, "screen") {
          Ok(r) => r,
          Err(e) => return ToolOutcome::err(e),
        };
        let wait = Wait {
          timeout: secs(input, "timeout_secs", 60.0, 3600.0),
          idle: input
            .get("idle_secs")
            .map(|_| secs(input, "idle_secs", 1.0, 3600.0)),
          screen,
        };
        let waiting = Waiting::new(&self.shells, thread, session_name, &session);
        let o = session.run(command, wait).await;
        waiting.done();
        let out = match o {
          Ok(o) => noted(describe(&o), approved),
          Err(e) => failed(session_name, e),
        };
        let out = if sandboxed { refusal_noted(out) } else { out };
        restarted_noted(
          restarted,
          fresh(created && restart == Restart::No, session_name, out),
        )
      }
      "shell_send" => {
        let session = match self.existing(thread, session_name).await {
          Ok(s) => s,
          Err(e) => return ToolOutcome::err(e),
        };
        let text = input.get("text").and_then(Value::as_str).unwrap_or("");
        let submit = input.get("submit").and_then(Value::as_bool) == Some(true);
        let mut keys: Vec<u8> = Vec::new();
        let mut enter_key = false;
        for k in input
          .get("keys")
          .and_then(Value::as_array)
          .into_iter()
          .flatten()
        {
          let Some(name) = k.as_str() else { continue };
          match key(name) {
            Some(b) => {
              enter_key |= b == b"\r";
              keys.extend_from_slice(b);
            }
            None => return ToolOutcome::err(format!("unknown key `{name}`")),
          }
        }
        // A program that asked for bracketed paste gets the text as a paste,
        // as a terminal pastes: whole, however long. Then a newline ending
        // it, or `submit`, is an Enter of its own once the screen settles
        // (sent with the paste, it is part of it and submits nothing).
        // Only a program holding the terminal: a mode left on by one that
        // crashed would put the markers into a shell's command line.
        let paste = session.bracketed_paste()
          && !text.is_empty()
          && matches!(session.status(), Status::Running { .. });
        let trimmed = text.trim_end_matches(['\r', '\n']);
        let ends_in_enter = trimmed.len() != text.len();
        let separate_enter = (paste && ends_in_enter) || submit;
        let body = if separate_enter { trimmed } else { text };
        let mut first = Vec::new();
        if paste {
          first.extend_from_slice(b"\x1b[200~");
          first.extend_from_slice(body.as_bytes());
          first.extend_from_slice(b"\x1b[201~");
        } else {
          first.extend_from_slice(body.as_bytes());
        }
        let enter =
          separate_enter || enter_key || (!paste && (text.contains('\n') || text.contains('\r')));
        // What was typed at the prompt without Enter is the start of the
        // line the next Enter runs: judged whole then (design §2.28). Keys
        // that edit or recall it (history, completion) make the line
        // unknown: with a guard judging, it is refused rather than run
        // unjudged.
        let at_prompt = matches!(session.status(), Status::AtPrompt { .. });
        let pkey = session_key(thread, session_name);
        let editing = keys.iter().any(|b| *b != b'\r');
        let guarded = self.hazard.as_ref().is_some_and(|g| !g.off());
        let line = if at_prompt {
          let mut pending = self.shells.pending.lock().expect("pending lock");
          if enter {
            let typed = pending.remove(&pkey).unwrap_or_default();
            if guarded && (editing || typed.contains('\u{0}')) {
              return ToolOutcome::err(
                "the hazard guard judges what runs: send the whole command line as text with \
                 Enter (not edited or recalled with keys)",
              );
            }
            format!("{typed}{text}")
          } else {
            let p = pending.entry(pkey.clone()).or_default();
            p.push_str(text);
            if editing {
              p.push('\u{0}');
            }
            String::new()
          }
        } else {
          self
            .shells
            .pending
            .lock()
            .expect("pending lock")
            .remove(&pkey);
          String::new()
        };
        // Input to a program running there (a REPL, an interpreter) is
        // judged as it is, best-effort: the guard sees what is typed, not
        // what the program makes of it.
        if !at_prompt
          && guarded
          && !text.trim().is_empty()
          && !self.rules.is_read_only()
          && let Some(g) = &self.hazard
          && g.role == crate::hazard::Role::User
        {
          let v = g
            .check(crate::hazard::Action::Shell {
              line: text.to_owned(),
              cwd: None,
              host: remote_of(session_name).map(|(h, _)| h.to_owned()),
            })
            .await;
          if let Some(v) = v {
            crate::hazard::record(&v);
            if v.fails() {
              return ToolOutcome::err(crate::hazard::unavailable(&v));
            }
            if v.asks() {
              let Some(approver) = &self.approver else {
                return ToolOutcome::err(format!(
                  "this input needs the user's approval, and nobody is here to give it{}",
                  crate::hazard::declined(&v)
                ));
              };
              let request = ApprovalRequest {
                verdict: Some(v.clone()),
                user_only: true,
                ..ApprovalRequest::new(
                  thread.clone(),
                  session_name.to_owned(),
                  crate::hazard::question(text, Some(&v)),
                )
              };
              if !approver(request).await.allow {
                return ToolOutcome::err(format!(
                  "the user declined this input{}",
                  crate::hazard::declined(&v)
                ));
              }
            }
          }
        }
        // A line entered at the prompt is a command, under the rules.
        let approved = if enter && at_prompt {
          // A read-only thread's rules of the sandbox hold only in a
          // session started in its read-only sandbox (not one started
          // before it was switched so, still open here).
          let sandboxed = session.sandboxed()
            && (!self.rules.is_read_only()
              || self
                .shells
                .read_only
                .lock()
                .expect("read-only lock")
                .contains(&session_key(thread, session_name)));
          match self
            .approve(thread, session_name, line.trim(), sandboxed)
            .await
          {
            Ok(approved) => approved,
            Err(e) => return ToolOutcome::err(e),
          }
        } else {
          false
        };
        let screen = match regex_of(input, "screen") {
          Ok(r) => r,
          Err(e) => return ToolOutcome::err(e),
        };
        let wait = Wait {
          timeout: secs(input, "timeout_secs", 10.0, 3600.0),
          idle: Some(secs(input, "idle_secs", 1.0, 3600.0)),
          screen,
        };
        let entered = enter && matches!(session.status(), Status::AtPrompt { .. });
        let waiting = entered.then(|| Waiting::new(&self.shells, thread, session_name, &session));
        let o = if separate_enter {
          let typed = session
            .send_minding(&first, Wait::prompt(Duration::ZERO))
            .await;
          match typed {
            Ok(_) => {
              session.settle(SETTLE, SETTLE_MAX).await;
              let mut rest = b"\r".to_vec();
              rest.extend_from_slice(&keys);
              // Entered at the prompt, the command is the text before it.
              session.name_command(body);
              session.send_minding(&rest, wait).await
            }
            Err(e) => Err(e),
          }
        } else {
          first.extend_from_slice(&keys);
          session.send_minding(&first, wait).await
        };
        if let Some(w) = waiting {
          w.done();
        }
        match o {
          Ok(o) => noted(describe(&o), approved),
          Err(e) => failed(session_name, e),
        }
      }
      "shell_view" => match self.existing(thread, session_name).await {
        Ok(s) => {
          let screen = s.screen();
          let state = match &screen.status {
            Status::AtPrompt { exit } => format!("at the prompt (last exit {exit})"),
            Status::Running { program, .. } => format!("running: {program}"),
            Status::Closed => "ended".into(),
          };
          ToolOutcome {
            ok: true,
            images: Vec::new(),
            spent: None,
            output: format!(
              "{state}; cursor at row {}, column {}{}\n\n{}",
              screen.cursor.0,
              screen.cursor.1,
              if screen.alternate {
                "; full-screen program"
              } else {
                ""
              },
              screen.text.trim_end()
            ),
            attachments: Vec::new(),
            blobs: Vec::new(),
            generated: Vec::new(),
          }
        }
        Err(e) => ToolOutcome::err(e),
      },
      "shell_close" => {
        let key = format!("{thread}:{session_name}");
        self.shells.forget(thread, session_name);
        self.shells.unmark_auto(thread, session_name);
        let s = self.shells.sessions.lock().await.remove(&key);
        if let Some(shared) = self.ssh.as_ref().and_then(std::sync::Weak::upgrade) {
          shared.ssh.forget(&key);
        }
        match s {
          Some(s) => {
            s.close().await;
            ToolOutcome {
              ok: true,
              output: "closed".into(),
              images: Vec::new(),
              spent: None,
              attachments: Vec::new(),
              blobs: Vec::new(),
              generated: Vec::new(),
            }
          }
          None => ToolOutcome::err(format!("no session {session_name}")),
        }
      }
      other => ToolOutcome::err(format!("no tool {other}")),
    }
  }
}

/// The session tools given `host` (design §2.20): which hosts, and how
/// sessions and approvals go there. Without a local shell (a phone),
/// `host` is required and what is only local goes.
fn with_hosts(defs: &mut Vec<ToolDef>, hosts: &[crate::api::SshHost]) {
  let local = stitch_shell::CAN_SPAWN;
  let listed: Vec<String> = hosts
    .iter()
    .map(|h| {
      let mut s = h.name.clone();
      let mut how = Vec::new();
      if !h.user.is_empty() || !h.address.is_empty() {
        how.push(format!(
          "{}{}",
          if h.user.is_empty() {
            String::new()
          } else {
            format!("{}@", h.user)
          },
          if h.address.is_empty() {
            &h.name
          } else {
            &h.address
          }
        ));
      }
      match crate::rules::HostApproval::parse(&h.approval) {
        Some(crate::rules::HostApproval::Allow) => how.push("trusted: everything runs".into()),
        Some(crate::rules::HostApproval::Ask) => how.push("kept to asking".into()),
        _ => {}
      }
      if !how.is_empty() {
        s.push_str(&format!(" ({})", how.join(", ")));
      }
      s
    })
    .collect();
  let names: Vec<&str> = hosts.iter().map(|h| h.name.as_str()).collect();
  let host = json!({
    "type": "string",
    "enum": names,
    "description": format!(
      "{} this SSH host: {}. A session there is keyed by host and session name (the same name on two hosts is two sessions); in tmux where the host has it, it outlives a dropped connection and is picked up where it was, the result saying it reconnected.",
      if local { "Instead of this machine, on" } else { "On" },
      listed.join("; ")
    ),
  });
  for d in defs.iter_mut() {
    let session_tool = matches!(
      d.name.as_str(),
      "shell_run"
        | "shell_send"
        | "shell_watch"
        | "shell_wait"
        | "shell_view"
        | "shell_close"
        | "job_stop"
    );
    if !session_tool {
      continue;
    }
    if let Some(props) = d
      .input_schema
      .get_mut("properties")
      .and_then(Value::as_object_mut)
    {
      props.insert("host".into(), host.clone());
      if !local {
        props.remove("outside");
      }
      if let Some(cwd) = props.get_mut("cwd") {
        cwd["description"] = json!(
          "Working directory, used only when the session is created (on a host it starts in the user's home: cd there)."
        );
      }
    }
    if !local && d.name != "job_stop" {
      let required = d
        .input_schema
        .as_object_mut()
        .map(|o| o.entry("required").or_insert_with(|| json!([])));
      if let Some(Value::Array(r)) = required {
        r.push(json!("host"));
      }
      d.description = d
        .description
        .replace("on this machine", "on an SSH host (`host`)");
    }
    if d.name == "shell_run" {
      d.description.push_str(
        " With `host`, it runs on that SSH host: what reaches beyond asks as in the sandbox (pushing, `rm -r` of anything but relative paths below where it runs, `sudo`, `systemctl`, packages, disks, the firewall), the rest runs, unless the host is trusted whole or kept to asking. A machine that runs Stitch is better reached by spawning a thread on its node.",
      );
    }
  }
  if !local {
    defs.retain(|d| d.name != "watch_file");
  }
}

impl ToolRunner for ShellTools {
  fn definitions(&self) -> Vec<ToolDef> {
    if self.rules.mode == "off" {
      Vec::new()
    } else {
      let hosts: Vec<crate::api::SshHost> = self
        .ssh
        .as_ref()
        .and_then(std::sync::Weak::upgrade)
        .map(|s| crate::ssh::hosts(&s))
        .unwrap_or_default();
      // No local shell (a phone): the tools are for hosts, when there are.
      if !stitch_shell::CAN_SPAWN && hosts.is_empty() {
        return Vec::new();
      }
      // What runs without asking, as it stands: the model can steer toward it.
      let mut defs = definitions();
      if !hosts.is_empty() {
        with_hosts(&mut defs, &hosts);
      }
      if let Some(run) = defs.iter_mut().find(|d| d.name == "shell_run") {
        run.description = run.description.replace(
          "Commands outside the allowed set wait for the user's approval.",
          &self.rules.describe(),
        );
        if self.sandbox.is_none()
          && let Some(props) = run
            .input_schema
            .get_mut("properties")
            .and_then(Value::as_object_mut)
        {
          props.remove("outside");
        }
      }
      defs
    }
  }

  fn call<'a>(
    &'a self,
    thread: &'a RecordId,
    _: &'a str,
    name: &'a str,
    input: &'a Value,
  ) -> BoxFuture<'a, ToolOutcome> {
    Box::pin(self.run(thread, name, input))
  }

  fn interrupt<'a>(
    &'a self,
    thread: &'a RecordId,
    name: &'a str,
    _: &'a Value,
  ) -> BoxFuture<'a, ()> {
    Box::pin(async move {
      if !matches!(name, "shell_run" | "shell_send") {
        return;
      }
      // The call was cut short before this runs: its command is being
      // stopped (see `Waiting`).
      let stopping = self
        .shells
        .stopping_calls
        .lock()
        .expect("stopping lock")
        .remove(thread.as_str());
      if let Some(task) = stopping {
        let _ = task.await;
      }
    })
  }
}

