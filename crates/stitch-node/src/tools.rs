/// A regular expression the model gave as `key`.
fn regex_of(input: &Value, key: &str) -> Result<Option<Regex>, String> {
  input
    .get(key)
    .and_then(Value::as_str)
    .map(|p| Regex::new(p).map_err(|e| format!("bad {key}: {e}")))
    .transpose()
}

/// What `shell_wait` and `shell_watch` wait for: a line (`pattern`), the
/// screen (`screen`, `screen_gone`, `quiet_secs`, all at once), else the
/// command's end.
fn until_of(input: &Value) -> Result<Until, String> {
  let line = regex_of(input, "pattern")?;
  let on = ScreenUntil {
    shows: regex_of(input, "screen")?,
    gone: regex_of(input, "screen_gone")?,
    quiet: quiet_of(input),
  };
  let screen = on.shows.is_some() || on.gone.is_some() || on.quiet.is_some();
  match (line, screen) {
    (Some(_), true) => Err("either a line `pattern` or screen conditions, not both".into()),
    (Some(re), false) => Ok(Until::Line(re)),
    (None, true) => Ok(Until::Screen(on)),
    (None, false) => Ok(Until::Done),
  }
}

/// The longest quiet a job or wait takes: a day.
const QUIET_MAX: f64 = 86_400.0;

/// `quiet_secs` as the model gave it, within reason (a huge or negative
/// number is no panic).
fn quiet_of(input: &Value) -> Option<Duration> {
  input
    .get("quiet_secs")
    .and_then(Value::as_f64)
    .map(|s| Duration::try_from_secs_f64(s.clamp(0.0, QUIET_MAX)).unwrap_or(Duration::ZERO))
}

/// A command a call entered and waits on. Cut short (the call
/// interrupted, its loop aborted), the command gets Ctrl+C, as a person at
/// the terminal would stop it, and again while it runs, within a bound
/// (`Session::stop_command`); the interrupt awaits that (`stopping_calls`).
/// Only a command the call entered: one left running before (a server) is
/// not the user's to stop here, nor one entered after.
struct Waiting {
  shells: Arc<Shells>,
  thread: String,
  name: String,
  session: Session,
  /// The command entered before the call's own.
  before: Option<std::time::Instant>,
  done: bool,
}

/// Ctrl+C at most this many times to stop a cut-short call's command, each
/// waiting this long for its prompt.
const STOP_TRIES: u32 = 3;
const STOP_EACH: Duration = Duration::from_secs(2);

impl Waiting {
  fn new(shells: &Arc<Shells>, thread: &RecordId, name: &str, session: &Session) -> Self {
    Waiting {
      shells: shells.clone(),
      thread: thread.to_string(),
      name: name.to_owned(),
      session: session.clone(),
      before: session.command().map(|c| c.started),
      done: false,
    }
  }

  /// The call had its answer.
  fn done(mut self) {
    self.done = true;
  }
}

impl Drop for Waiting {
  fn drop(&mut self) {
    if self.done {
      return;
    }
    let Ok(rt) = tokio::runtime::Handle::try_current() else {
      return;
    };
    let session = self.session.clone();
    let before = self.before;
    let (thread, name) = (self.thread.clone(), self.name.clone());
    let task = rt.spawn(async move {
      match session.stop_command(before, STOP_TRIES, STOP_EACH).await {
        Ok(true) => {}
        // The session says it is busy with it; the next call is told so.
        Ok(false) => eprintln!(
          "thread {thread}: session {name}: an interrupted call's command still runs after {STOP_TRIES} Ctrl+C"
        ),
        Err(e) => eprintln!("thread {thread}: session {name}: stopping an interrupted call's command: {e}"),
      }
    });
    self
      .shells
      .stopping_calls
      .lock()
      .expect("stopping lock")
      .insert(self.thread.clone(), task);
  }
}

