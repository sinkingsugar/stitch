pub type BoxFuture<'a, T> = Pin<Box<dyn Future<Output = T> + Send + 'a>>;

/// What a tool call returned.
#[derive(Clone, Debug, Default, PartialEq)]
pub struct ToolOutcome {
  pub ok: bool,
  pub output: String,
  /// Images generated by a tool, copied into the blob store by the loop.
  pub images: Vec<ToolImage>,
  /// Blobs a tool stored, shown with its result (an app's manifest).
  pub attachments: Vec<stitch_records::Attachment>,
  /// Images a tool made for the reply (`generate_image`), stored: they
  /// become the calling turn's reply's attachments, as an image model's
  /// own images do.
  pub generated: Vec<stitch_records::Attachment>,
  /// Blobs the result references besides, so nodes that pull every blob
  /// pull them (an app's files).
  pub blobs: Vec<stitch_records::BlobHash>,
  /// What a tool spent on models (threads `wait` had): counted like the thread's
  /// own steps, budgets included.
  pub spent: Option<Spent>,
}

/// A model call made by a tool.
#[derive(Clone, Debug, PartialEq)]
pub struct Spent {
  pub model: String,
  pub usage: stitch_providers::Usage,
  pub usd: Option<f64>,
}

/// What the calls a tool's call made in turn spent (a script's
/// `Tool.Call`s and `Decide`s), kept outside the call's future so a call
/// stopped midway still has what it spent counted (`spending_into`).
#[derive(Debug, Default)]
pub(crate) struct AlsoSpent {
  pub spent: Vec<Spent>,
  /// Paid decisions made so far in the call (`decide::admit`).
  pub decisions: usize,
  /// What the thread had left of its budget when the call began (read
  /// once, by the first decision that needs it): `Some(None)`, no budget.
  pub left: Option<Option<f64>>,
}

impl AlsoSpent {
  pub(crate) fn usd(&self) -> f64 {
    self.spent.iter().filter_map(|s| s.usd).sum()
  }
}

pub(crate) type AlsoSpentCell = Arc<std::sync::Mutex<AlsoSpent>>;

tokio::task_local! {
  static ALSO_SPENT: AlsoSpentCell;
}

/// Runs a tool call, keeping what the calls it made spent.
#[cfg(test)]
pub(crate) async fn spending<T>(f: impl std::future::Future<Output = T>) -> (T, Vec<Spent>) {
  let acc = AlsoSpentCell::default();
  let out = spending_into(acc.clone(), f).await;
  let v = std::mem::take(&mut acc.lock().expect("spent lock").spent);
  (out, v)
}

/// Runs a tool call, what the calls it made spend kept in `acc` as they
/// spend it: read it however the call ended.
pub(crate) async fn spending_into<T>(
  acc: AlsoSpentCell,
  f: impl std::future::Future<Output = T>,
) -> T {
  ALSO_SPENT.scope(acc, f).await
}

/// Counts what a call made inside another spent (outside `spending`, it
/// is the caller's to count: nothing kept).
pub(crate) fn also_spent(s: Spent) {
  let _ = ALSO_SPENT.try_with(|v| v.lock().expect("spent lock").spent.push(s));
}

/// What the tool call running in this task has spent so far, and its
/// accumulator (none outside `spending`).
pub(crate) fn also_spent_cell() -> Option<AlsoSpentCell> {
  ALSO_SPENT.try_with(Clone::clone).ok()
}

#[derive(Clone, Debug, PartialEq, Eq)]
pub struct ToolImage {
  pub path: PathBuf,
  pub media_type: String,
}

impl ToolOutcome {
  pub(crate) fn ok(output: impl Into<String>) -> Self {
    ToolOutcome {
      ok: true,
      output: output.into(),
      images: Vec::new(),
      spent: None,
      attachments: Vec::new(),
      blobs: Vec::new(),
      generated: Vec::new(),
    }
  }

  pub(crate) fn err(output: impl Into<String>) -> Self {
    ToolOutcome {
      ok: false,
      output: output.into(),
      images: Vec::new(),
      spent: None,
      attachments: Vec::new(),
      blobs: Vec::new(),
      generated: Vec::new(),
    }
  }
}

/// Tools for a chat loop.
pub trait ToolRunner: Send + Sync {
  /// Before each model call: whatever `definitions` needs that takes
  /// waiting (MCP servers started, their tools listed).
  fn prepare(&self) -> BoxFuture<'_, ()> {
    Box::pin(async {})
  }
  fn definitions(&self) -> Vec<ToolDef>;
  /// Runs tool call `call` (its ID in the transcript) of `thread`.
  fn call<'a>(
    &'a self,
    thread: &'a RecordId,
    call: &'a str,
    name: &'a str,
    input: &'a Value,
  ) -> BoxFuture<'a, ToolOutcome>;
  /// The user stopped call `name` of `thread` while it ran: stops what it
  /// started.
  fn interrupt<'a>(
    &'a self,
    thread: &'a RecordId,
    name: &'a str,
    input: &'a Value,
  ) -> BoxFuture<'a, ()> {
    let _ = (thread, name, input);
    Box::pin(async {})
  }
  /// A tool's output as the model and the transcript get it: every secret
  /// value the node holds replaced by `«secret:<name>»` (design §2.19).
  fn redact(&self, text: String) -> String {
    text
  }
  /// Before each model call: why the loop must stop instead, if it must
  /// (an app's thread past its grant or its family's money, design
  /// §2.22). Nothing by default.
  fn admit<'a>(&'a self, thread: &'a RecordId) -> BoxFuture<'a, Option<String>> {
    let _ = thread;
    Box::pin(async { None })
  }
  /// What a model call of the loop, or one a tool made, spent: `model`,
  /// its usage, and its cost when the provider gave it.
  fn metered(
    &self,
    thread: &RecordId,
    model: &str,
    usage: &stitch_providers::Usage,
    usd: Option<f64>,
  ) {
    let _ = (thread, model, usage, usd);
  }
  /// A turn of `thread` took the `taken` steps it had: whether the user
  /// grants `more` again. Asked only in a chat the user is in (an
  /// approval: on their clients and pushed to their phones, yolo or not);
  /// elsewhere the turn wraps up.
  fn more_steps<'a>(&'a self, thread: &'a RecordId, taken: u64, more: u64) -> BoxFuture<'a, bool> {
    let _ = (thread, taken, more);
    Box::pin(async { false })
  }
}

/// The `session` of an approval asking for more steps (`more_steps`):
/// clients show its `command` as the question it is, not a command to run.
pub const STEPS_SESSION: &str = "steps";

