pub use crate::rules::{DEFAULT_ALLOW, Rules};

/// A request for the user's approval.
#[derive(Clone)]
pub struct ApprovalRequest {
  /// The thread whose agent wants to run it.
  pub thread: RecordId,
  pub session: String,
  pub command: String,
  /// What answering "always" allows from then on in the thread's place
  /// (command prefixes, tools of `grant_server`, or Otter tools with
  /// `grant_otter`); empty: no such answer.
  pub grant: Vec<String>,
  /// The MCP server whose tools (unprefixed) `grant` names; none: `grant`
  /// is command prefixes, or Otter tools.
  pub grant_server: Option<String>,
  /// `grant` names Otter tools (`crate::otter`).
  pub grant_otter: bool,
  /// Whether the rules allow it by now (yolo turned on, a prefix granted
  /// meanwhile): a waiting question then goes.
  pub allowed_now: Option<Arc<dyn Fn() -> bool + Send + Sync>>,
  /// Asked for the user's browser (design §2.18): `grant` names sites,
  /// a screenshot may go with it, and the page may answer it first.
  pub browser: Option<BrowserAsk>,
  /// What the user reads before answering, written by the node (a
  /// landing's facts and diff, docs/self-improve.md §4): such a question
  /// is the user's alone to answer, never a thread's or what one started.
  pub review: Option<Review>,
  /// The hazard guard's verdict on what is asked (design §2.28), kept on
  /// the question record (the user's answers calibrate it).
  pub(crate) verdict: Option<crate::hazard::Verdict>,
  /// The user's alone to answer, never a thread's commands (as a review
  /// is): what the hazard guard stopped.
  pub user_only: bool,
  /// A read-only room participant asks (design §2.27): `command` is what
  /// it wants, in words, and "always" makes the thread writable (`grant`
  /// says so) instead of granting anything in its place.
  pub writable: bool,
}

