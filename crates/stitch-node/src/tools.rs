  /// Issue svf3 (2026-11-22): a read-only room participant's command the
  /// user allowed once runs in a session started writable, which the
  /// sync asking started (`Shared::close_switched`, closing the writable
  /// sessions of threads read-only by their record) closed as one a
  /// switch to read-only left, when it ended after the session started:
  /// the command came back "the session has ended". That
  /// session is not listed among the writable ones; a writable thread's
  /// still is, and the participant's next session starts read-only.
  #[tokio::test]
  async fn a_session_allowed_once_is_not_closed_as_switched_to_read_only() {
    use crate::hazard::Mode;
    let (mut t, _) = guarded("ask", Mode::Off, |_| panic!("not asked"), true);
    t.hazard = None;
    t.rules.read_only = true;
    let ask = crate::rules::RoomAsk::new("Opus", "Shell");
    t.rules.room_ask = Some(ask.clone());
    let participant = thread();
    ask.allow_once(&session_key(&participant, "main"));
    let (once, created) = t.session(&participant, "main", None, false).await.unwrap();
    assert!(created);
    assert!(
      t.shells.writable_threads().await.is_empty(),
      "a session allowed once is not one left writable"
    );
    // A writable thread's session is.
    let (mut w, _) = guarded("ask", Mode::Off, |_| panic!("not asked"), true);
    w.hazard = None;
    w.shells = t.shells.clone();
    let writer: RecordId = "2026-11-13T100000Z-gamer-wxyz".parse().unwrap();
    let (writable, _) = w.session(&writer, "main", None, false).await.unwrap();
    assert_eq!(t.shells.writable_threads().await, vec![writer.clone()]);
    // The participant's next call starts its session again read-only.
    let (again, created) = t.session(&participant, "main", None, false).await.unwrap();
    assert!(created);
    assert_eq!(once.status(), Status::Closed);
    assert!(
      t.shells
        .read_only
        .lock()
        .unwrap()
        .contains(&session_key(&participant, "main"))
    );
    assert!(t.shells.once.lock().unwrap().is_empty());
    assert_eq!(t.shells.writable_threads().await, vec![writer.clone()]);
    again.close().await;
    writable.close().await;
  }

