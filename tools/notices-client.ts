// The web client bundle's third-party notices (notices/client.txt): the
// packages its runtime dependencies pull in, by apps/client/bun.lock, with
// each one's license text from node_modules (`bun install --frozen-lockfile`
// first). Type declarations and build tools (devDependencies) are not in
// the bundle. `just notices` runs it:
//   bun tools/notices-client.ts <apps/client> <output>
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const [clientDir, out] = process.argv.slice(2);
if (!clientDir || !out) {
  console.error("usage: notices-client.ts <apps/client> <output>");
  process.exit(2);
}

// bun.lock is JSON with trailing commas.
const lockText = readFileSync(join(clientDir, "bun.lock"), "utf8").replace(/,(\s*[}\]])/g, "$1");
const lock = JSON.parse(lockText);
const packages: Record<string, [string, string, { dependencies?: Record<string, string> }]> =
  lock.packages;

// The runtime closure from the workspace's dependencies.
const seen = new Set<string>();
const queue = Object.keys(lock.workspaces[""].dependencies ?? {});
while (queue.length) {
  const name = queue.shift()!;
  if (seen.has(name)) continue;
  const entry = packages[name];
  if (!entry) throw new Error(`${name} is not in bun.lock`);
  seen.add(name);
  queue.push(...Object.keys(entry[2]?.dependencies ?? {}));
}

const licenseFile = (dir: string): string | undefined =>
  readdirSync(dir)
    .filter((f) => /^(licen[cs]e|copying)(\.(md|txt))?$/i.test(f))
    .sort()[0];

const parts: string[] = [];
const index: string[] = [];
for (const name of [...seen].sort()) {
  const dir = join(clientDir, "node_modules", name);
  const pkg = JSON.parse(readFileSync(join(dir, "package.json"), "utf8"));
  const license = typeof pkg.license === "string" ? pkg.license : pkg.license?.type;
  if (!license) throw new Error(`${name}: no license in package.json`);
  const file = licenseFile(dir);
  if (!file) throw new Error(`${name}: no license file in the package`);
  const repo = typeof pkg.repository === "string" ? pkg.repository : pkg.repository?.url;
  index.push(`  ${name} ${pkg.version} (${license})`);
  parts.push(
    [
      "=".repeat(80),
      `${name} ${pkg.version} (${license})${repo ? `\n${repo.replace(/^git\+/, "")}` : ""}`,
      "",
      readFileSync(join(dir, file), "utf8").trimEnd(),
      "",
    ].join("\n"),
  );
}

const header = `THIRD-PARTY NOTICES: THE WEB CLIENT

Generated by \`just notices\` (tools/notices-client.ts) from apps/client/bun.lock:
the npm packages bundled into the web client (apps/client/dist, embedded in
the node). Do not edit by hand.

Packages:
${index.join("\n")}

`;
writeFileSync(out, header + parts.join("\n"));
