#!/usr/bin/env bash
# The generated third-party notices in notices/ (`just notices`):
#   notices.sh [rust|client|llama ...]   regenerate them (default: all)
#   notices.sh --check [part ...]        fail when one differs from a fresh run
#
# - rust:   notices/rust.txt, cargo-about (about.toml, notices/rust.hbs) over
#           Cargo.lock; needs cargo-about (`cargo install cargo-about
#           --locked --features cli`).
# - client: notices/client.txt, the web client's bundled npm packages
#           (tools/notices-client.ts over apps/client/bun.lock); needs bun.
# - llama:  notices/llama.txt, llama.cpp's license and those of the
#           libraries it vendors that Stitch builds (the submodule).
# notices/applibs.txt and notices/README.md are kept by hand.
set -euo pipefail
root=$(cd "$(dirname "$0")/.." && pwd)
cd "$root"
export PATH="$HOME/.bun/bin:$PATH"

check=false
if [ "${1-}" = --check ]; then
  check=true
  shift
fi
parts=("$@")
[ ${#parts[@]} -gt 0 ] || parts=(rust client llama)

out_dir=notices
if $check; then
  out_dir=$(mktemp -d)
  trap 'rm -rf "$out_dir"' EXIT
fi

rust() {
  # Every target's crates fetched, so cargo-about reads them offline (and
  # never falls back to fetching license texts from the network, which
  # would make the output depend on it).
  cargo fetch --locked >/dev/null
  cargo about generate --workspace --frozen --fail \
    -o "$out_dir/rust.txt" notices/rust.hbs
}

client() {
  (cd apps/client && bun install --frozen-lockfile >/dev/null)
  bun tools/notices-client.ts apps/client "$out_dir/client.txt"
}

# The license block a single-header library ends with: from the line that
# opens it to the end of that comment.
license_block() {
  awk -v start="$2" 'index($0, start) { on = 1 } on { print } on && /\*\// { exit }' "$1"
}

llama() {
  local src=crates/stitch-llama/llama.cpp
  [ -f "$src/LICENSE" ] || { echo "llama.cpp is not checked out (git submodule update --init)" >&2; exit 1; }
  {
    echo "THIRD-PARTY NOTICES: LLAMA.CPP"
    echo
    echo "Generated by \`just notices\` (tools/notices.sh) from the llama.cpp submodule"
    echo "(crates/stitch-llama/llama.cpp, commit $(git rev-parse HEAD:"$src")), built into"
    echo "Stitch by stitch-llama: llama.cpp's own license, the ones in its licenses/,"
    echo "and those of the libraries it vendors. Do not edit by hand."
    echo
    local sep
    sep=$(printf '=%.0s' {1..80})
    echo "$sep"
    echo "llama.cpp and ggml (MIT)"
    echo
    cat "$src/LICENSE"
    for f in "$src"/licenses/*; do
      echo
      echo "$sep"
      echo "llama.cpp: licenses/$(basename "$f")"
      echo
      cat "$f"
    done
    while IFS= read -r f; do
      echo
      echo "$sep"
      echo "llama.cpp: ${f#"$src"/}"
      echo
      cat "$f"
    done < <(find "$src/vendor" -iname 'LICENSE*' | LC_ALL=C sort)
    echo
    echo "$sep"
    echo "llama.cpp: vendor/stb/stb_image.h (Sean Barrett; MIT or public domain)"
    echo
    license_block "$src/vendor/stb/stb_image.h" "This software is available under 2 licenses"
    echo
    echo "$sep"
    echo "llama.cpp: vendor/miniaudio/miniaudio.h (David Reid; public domain or MIT-0)"
    echo
    license_block "$src/vendor/miniaudio/miniaudio.h" "This software is available as a choice of the following licenses"
    echo
    echo "$sep"
    echo "llama.cpp: vendor/sheredom/subprocess.h (Neil Henning; public domain)"
    echo
    license_block "$src/vendor/sheredom/subprocess.h" "This is free and unencumbered software"
    echo
    echo "$sep"
    echo "llama.cpp: vendor/hash/sha1 (Steve Reid; public domain)"
    echo
    sed -n '1,4p' "$src/vendor/hash/sha1/sha1.c"
  } >"$out_dir/llama.txt"
}

# The tool a part needs. Missing: an error, except for a check outside CI
# (`just check` on a machine without it), which skips that part, said.
needs() {
  case $1 in
    rust) command -v cargo-about >/dev/null ;;
    client) command -v bun >/dev/null ;;
    llama) true ;;
  esac
}

done_parts=()
for p in "${parts[@]}"; do
  case $p in
    rust | client | llama) ;;
    *) echo "unknown part: $p (rust, client, llama)" >&2; exit 2 ;;
  esac
  if ! needs "$p"; then
    tool=$([ "$p" = rust ] && echo "cargo-about (cargo install cargo-about --locked --features cli)" || echo bun)
    if $check && [ -z "${CI-}" ]; then
      echo "notices: $p not checked: $tool is not installed" >&2
      continue
    fi
    echo "notices: $p needs $tool" >&2
    exit 1
  fi
  "$p"
  done_parts+=("$p")
done
parts=("${done_parts[@]+"${done_parts[@]}"}")

if $check; then
  stale=()
  for p in "${parts[@]+"${parts[@]}"}"; do
    cmp -s "$out_dir/$p.txt" "notices/$p.txt" || stale+=("notices/$p.txt")
  done
  if [ ${#stale[@]} -gt 0 ]; then
    echo "stale: ${stale[*]} (run \`just notices\` and commit the result)" >&2
    exit 1
  fi
  echo "notices up to date: ${parts[*]:-none}"
fi
